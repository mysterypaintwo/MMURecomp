#!/usr/bin/env python3
"""Recover top-level level/menu flow evidence from MMU.exe.

This tool is intentionally conservative. It walks the RTTI vtables for every
Level*/Menu* class, scans the first part of each virtual function for printable
.rdata strings and calls to the known state helpers, and writes a compact
evidence report to docs/game_flow.txt.

Important: a referenced string is not automatically a state name. BaseLevel's
"Victory"/"VictoryZ" references, for example, are passed to a global cue
setter (0x4026b0), while menu classes call the real setState (0x4405c0). The
report includes call targets so those two cases can be told apart.

Usage:
  python3 tools/analyze_game_flow.py MMU.exe [output.txt]
"""

import os
import sys
from collections import Counter

from capstone import CS_ARCH_X86, CS_MODE_32, Cs
from capstone.x86 import X86_OP_IMM, X86_OP_MEM

from analyze_rtti import PE
from disasm import find_vftables

SET_STATE = 0x4405C0
GLOBAL_SET = 0x4026B0
DT = 0x43E510
GET_STATE = 0x401580
NAMES = {
    SET_STATE: "setState",
    GLOBAL_SET: "global_cue_or_state_setter",
    DT: "dt",
    GET_STATE: "getState",
}

LEVEL_CLASSES = ("Level",)
MENU_CLASSES = ("Menu",)


def short_class(name):
    """Turn .?AVLevelWilyOne@@ into LevelWilyOne."""
    if name.startswith(".?AV"):
        return name[4:-2] if name.endswith("@@") else name[4:]
    return name


def cstring(pe, va, min_len=3, max_len=80):
    """Return a printable .rdata C string at a VA, or None."""
    if va < pe.image_base:
        return None
    rva = va - pe.image_base
    if not pe.in_rdata(rva):
        return None
    off = pe.rva_to_off(rva)
    if off is None:
        return None
    raw = pe.data[off:off + max_len + 1].split(b"\0", 1)[0]
    if not (min_len <= len(raw) <= max_len):
        return None
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        return None
    if not all(0x20 <= ord(ch) < 0x7F for ch in text):
        return None
    return text


def target_of(ins):
    for op in ins.operands:
        if op.type == X86_OP_IMM:
            return op.imm & 0xFFFFFFFF
        if (op.type == X86_OP_MEM and op.mem.base == 0 and
                op.mem.index == 0):
            return op.mem.disp & 0xFFFFFFFF
    return None


def scan_function(pe, va, limit=0x700):
    off = pe.rva_to_off(va - pe.image_base)
    if off is None:
        return [], [], []
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    strings = []
    calls = []
    state_writes = []
    last_string = None
    for ins in md.disasm(pe.data[off:off + limit], va):
        if ins.mnemonic in ("int3", "int", "ret", "retf"):
            break
        for op in ins.operands:
            if op.type == X86_OP_IMM:
                text = cstring(pe, op.imm & 0xFFFFFFFF)
                if text:
                    strings.append(text)
                    last_string = text
        if ins.mnemonic == "call":
            target = target_of(ins)
            if target is None:
                continue
            if target in NAMES or pe.in_text(target):
                calls.append((target, NAMES.get(target)))
            if target in (SET_STATE, GLOBAL_SET) and last_string:
                state_writes.append((target, last_string))
                last_string = None
    return strings, calls, state_writes


def fmt_list(items):
    return ", ".join(items) if items else "-"


def analyse(pe):
    tables = find_vftables(pe)
    selected = []
    for name, entries in tables.items():
        simple = short_class(name)
        is_level = any(token in simple for token in LEVEL_CLASSES)
        is_menu = any(token in simple for token in MENU_CLASSES)
        # mmu::Level is the protobuf asset type, not a runtime stage class.
        if is_level and "@mmu" in simple:
            continue
        if not (is_level or is_menu):
            continue
        for vft, funcs in entries:
            selected.append((simple, is_menu, vft, funcs))
    selected.sort(key=lambda item: (item[1], item[0], item[2]))

    lines = []
    lines.append("MMU top-level flow evidence (generated by tools/analyze_game_flow.py)")
    lines.append("image base 0x%x" % pe.image_base)
    lines.append("")
    lines.append("Notes:")
    lines.append("- Level vtables: slot 0 is the destructor, slot 1 is the per-frame driver.")
    lines.append("- setState is 0x4405c0; 0x4026b0 is the global cue/state setter used by BaseLevel.")
    lines.append("- A string reference is evidence, not proof of a state name; check the call target.")
    lines.append("")

    all_strings = Counter()
    for simple, is_menu, vft, funcs in selected:
        kind = "menu" if is_menu else "level"
        lines.append("=== %s (%s) vftable 0x%x, %d slots ===" %
                     (simple, kind, vft, len(funcs)))
        for slot, va in enumerate(funcs):
            strings, calls, state_writes = scan_function(pe, va)
            all_strings.update(strings)
            unique = list(dict.fromkeys(strings))
            state_text = []
            for target, text in state_writes:
                label = NAMES.get(target, hex(target))
                state_text.append("%s(%r)" % (label, text))
            call_text = []
            for target, label in calls:
                call_text.append("0x%x%s" % (target,
                                 "(" + label + ")" if label else ""))
            lines.append("  slot %-2d 0x%06x" % (slot, va))
            lines.append("    strings: %s" % fmt_list(unique[:12]))
            lines.append("    writes:  %s" % fmt_list(state_text))
            lines.append("    calls:   %s" % fmt_list(list(dict.fromkeys(call_text))[:12]))
        lines.append("")

    lines.append("=== most referenced strings in level/menu callbacks ===")
    for text, count in all_strings.most_common(60):
        lines.append("%4d  %s" % (count, text))
    lines.append("")
    return lines


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    pe = PE(open(sys.argv[1], "rb").read())
    lines = analyse(pe)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "docs", "game_flow.txt")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("\n".join(lines[:40]))
    print("... wrote %s (%d lines)" % (out, len(lines)))
    return 0


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    sys.exit(main())
