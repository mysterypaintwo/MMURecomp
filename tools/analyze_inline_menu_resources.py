#!/usr/bin/env python3
"""Recover inline .xspr push evidence from recovered menu constructors.

The 20 classes in docs/state_graph.txt whose registered class name contains
`Menu` build part or all of their UI from inline calls rather than from the
static supplier arrays recovered by analyze_menu_items.py. This tool reads each
class constructor region (split from .text at int3 padding) and records every
push of a printable .rdata string whose exact value ends in `.xspr`.

Each row preserves the class name, vftable VA, constructor region, push VA,
string VA, exact path, and the original non-reflected CRC-32 key. Duplicate
paths and duplicate keys are retained. No resource role, weapon meaning, slot,
or runtime behavior is inferred.

Usage:
  analyze_inline_menu_resources.py MMU.exe report.txt header.h
"""

import bisect
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from analyze_enemy_edge_facts import read
from analyze_game_flow import cstring
from analyze_rtti import PE
from analyze_state_graph import text_regions
from capstone import CS_ARCH_X86, CS_MODE_32, Cs
from crack_hash import mmu_crc32

TOOL = "tools/analyze_inline_menu_resources.py"
HEADER_RE = re.compile(
    r"^=== (\S+) vftable=(0x[0-9a-f]+) ctor=(0x[0-9a-f]+) ===$", re.MULTILINE)
MD = Cs(CS_ARCH_X86, CS_MODE_32)


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def menu_constructors(text):
    rows = []
    for match in HEADER_RE.finditer(text):
        class_name, vftable, ctor = match.groups()
        if "Menu" not in class_name:
            continue
        rows.append((class_name, int(vftable, 16), int(ctor, 16)))
    return rows


def collect(pe, base, data, bounds, class_name, vftable, ctor):
    index = bisect.bisect_right(bounds, ctor) - 1
    if index < 0 or index + 1 >= len(bounds):
        raise RuntimeError("constructor 0x%x outside .text" % ctor)
    start, end = bounds[index], bounds[index + 1]
    resources = []
    sequence = 0
    for row in MD.disasm(data[start - base:end - base], start):
        if row.mnemonic != "push":
            continue
        try:
            string_va = int(row.op_str, 16)
        except ValueError:
            continue
        if not pe.in_rdata(string_va - pe.image_base):
            continue
        path = cstring(pe, string_va, 3, 200)
        if not path or not path.lower().endswith(".xspr"):
            continue
        resources.append({
            "class": class_name,
            "vftable": vftable,
            "ctor": ctor,
            "regionEnd": end,
            "sequence": sequence,
            "pushVa": row.address,
            "stringVa": string_va,
            "key": mmu_crc32(path.encode()),
            "path": path,
        })
        sequence += 1
    return resources, start, end


def write_report(path, resources, constructors, regions):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by %s\n" % TOOL)
        out.write("Exact .rdata string pushes ending in .xspr inside the\n")
        out.write("int3-delimited constructor region of each recovered *Menu class.\n")
        out.write("classes=%d resources=%d unique_paths=%d\n\n" %
                  (len(constructors), len(resources),
                   len(set(r["path"] for r in resources))))
        for class_name, vftable, ctor in constructors:
            start, end = regions[ctor]
            rows = [r for r in resources if r["class"] == class_name]
            out.write("=== %s vftable=0x%x ctor=0x%x region=0x%x..0x%x "
                      "resources=%d ===\n" %
                      (class_name, vftable, ctor, start, end, len(rows)))
            for row in rows:
                out.write("  seq=%-2d push=0x%06x string=0x%06x key=0x%08x %s\n" %
                          (row["sequence"], row["pushVa"], row["stringVa"],
                           row["key"], row["path"]))
            out.write("\n")


def write_header(path, resources, constructors, regions):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from MMU.exe." % TOOL,
        "// Exact .xspr string pushes inside int3-delimited *Menu constructor regions.",
        "// Keys are the original non-reflected CRC-32 of the exact path.",
        "struct InlineMenuResource {",
        "    std::string_view className;",
        "    u32 vftable;",
        "    u32 constructorVa;",
        "    u32 regionEnd;",
        "    u16 sequence;",
        "    u32 pushVa;",
        "    u32 stringVa;",
        "    u32 key;",
        "    std::string_view path;",
        "};",
        "",
        "inline constexpr InlineMenuResource kInlineMenuResources[] = {",
    ]
    for row in resources:
        lines.append(
            "    {%s, 0x%06xu, 0x%06xu, 0x%06xu, %du, 0x%06xu, 0x%06xu, "
            "0x%08xu, %s}," %
            (cpp_string(row["class"]), row["vftable"], row["ctor"],
             row["regionEnd"], row["sequence"], row["pushVa"],
             row["stringVa"], row["key"], cpp_string(row["path"])))
    lines.extend([
        "};",
        "",
        "inline const InlineMenuResource* firstInlineMenuResource(u32 key) {",
        "    for (const InlineMenuResource& resource : kInlineMenuResources)",
        "        if (resource.key == key) return &resource;",
        "    return nullptr;",
        "}",
        "",
        "inline const InlineMenuResource* firstInlineMenuResource(std::string_view path) {",
        "    for (const InlineMenuResource& resource : kInlineMenuResources)",
        "        if (resource.path == path) return &resource;",
        "    return nullptr;",
        "}",
        "",
        "inline const InlineMenuResource* firstInlineMenuResource(std::string_view className, u16 sequence) {",
        "    for (const InlineMenuResource& resource : kInlineMenuResources)",
        "        if (resource.className == className && resource.sequence == sequence)",
        "            return &resource;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    exe, report, header = sys.argv[1:]
    root = os.path.dirname(os.path.dirname(report))
    pe = PE(open(exe, "rb").read())
    base, data, bounds = text_regions(pe)
    constructors = menu_constructors(
        read(os.path.join(root, "docs", "state_graph.txt")))
    resources = []
    regions = {}
    for class_name, vftable, ctor in constructors:
        rows, start, end = collect(pe, base, data, bounds, class_name,
                                    vftable, ctor)
        resources.extend(rows)
        regions[ctor] = (start, end)
    write_report(report, resources, constructors, regions)
    write_header(header, resources, constructors, regions)
    print("classes=%d resources=%d unique_paths=%d" %
          (len(constructors), len(resources),
           len(set(r["path"] for r in resources))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
