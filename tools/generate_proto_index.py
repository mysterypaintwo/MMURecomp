#!/usr/bin/env python3
"""Generate a portable raw-schema index from proto/*.proto.

The six proto2 schemas are offline reconstruction artifacts. This tool copies
their exact source lines, package/syntax declarations, message names and field
declarations into a C++ header so the SDL2 harness can query them without
reading the source tree at runtime. No field is renamed or assigned gameplay
meaning.

Usage:
  generate_proto_index.py [root] [header.h]
"""

import glob
import os
import re
import sys

SYNTAX_RE = re.compile(r'^syntax\s*=\s*"([^"]+)"\s*;\s*$')
PACKAGE_RE = re.compile(r'^package\s+([^;]+)\s*;\s*$')
MESSAGE_RE = re.compile(r'^message\s+([A-Za-z_]\w*)\s*\{\s*$')
FIELD_RE = re.compile(
    r'^\s*((?:optional|required|repeated))\s+(\S+)\s+([A-Za-z_]\w*)\s*=\s*(\d+)'
    r'(?:\s*\[[^\]]*\])?\s*;\s*$')
TOOL = "tools/generate_proto_index.py"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_lines(path):
    with open(path, "r", encoding="utf-8") as handle:
        return [line.rstrip("\r\n") for line in handle]


def parse_schema(path):
    name = os.path.basename(path)[:-len(".proto")]
    lines = read_lines(path)
    syntax = ""
    package = ""
    messages = []
    fields = []
    current = None
    for line in lines:
        match = SYNTAX_RE.match(line)
        if match:
            syntax = match.group(1)
            continue
        match = PACKAGE_RE.match(line)
        if match:
            package = match.group(1)
            continue
        match = MESSAGE_RE.match(line)
        if match:
            current = match.group(1)
            messages.append(current)
            continue
        if line.strip() == "}":
            current = None
            continue
        match = FIELD_RE.match(line)
        if match and current is not None:
            fields.append({
                "schema": name,
                "message": current,
                "label": match.group(1),
                "type": match.group(2),
                "name": match.group(3),
                "number": int(match.group(4)),
                "line": line,
            })
    return {
        "name": name,
        "syntax": syntax,
        "package": package,
        "messages": messages,
        "fields": fields,
        "source": "".join(line + "\n" for line in lines),
    }


def cpp_source_line(value):
    value = value.replace("\\", "\\\\").replace('"', '\\"')
    value = value.replace("\n", "\\n").replace("\r", "\\r")
    return '"' + value + '"'


def emit_source(lines, value):
    chunks = value.splitlines(keepends=True)
    for i in range(0, len(chunks), 4):
        lines.append("        " + " ".join(cpp_source_line(chunk) for chunk in chunks[i:i + 4]))


def write_header(path, schemas):
    lines = [
        "#pragma once",
        "",
        '#include "mmu/core/Types.h"',
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from proto/*.proto." % TOOL,
        "// Exact source lines and declared identifiers are copied verbatim.",
        "struct ProtoSchema {",
        "    std::string_view name;",
        "    std::string_view syntax;",
        "    std::string_view package;",
        "    u32 messageOffset;",
        "    u16 messageCount;",
        "    u32 fieldOffset;",
        "    u16 fieldCount;",
        "    std::string_view source;",
        "};",
        "",
        "struct ProtoMessage {",
        "    std::string_view schema;",
        "    std::string_view name;",
        "    u32 fieldOffset;",
        "    u16 fieldCount;",
        "};",
        "",
        "struct ProtoField {",
        "    std::string_view schema;",
        "    std::string_view message;",
        "    std::string_view label;",
        "    std::string_view type;",
        "    std::string_view name;",
        "    u32 number;",
        "    std::string_view sourceLine;",
        "};",
        "",
        "inline constexpr ProtoSchema kProtoSchemas[] = {",
    ]
    message_offset = 0
    field_offset = 0
    for schema in schemas:
        lines.append(
            "    {%s, %s, %s, %du, %du, %du, %du," %
            (cpp_string(schema["name"]), cpp_string(schema["syntax"]),
             cpp_string(schema["package"]), message_offset,
             len(schema["messages"]), field_offset, len(schema["fields"])))
        emit_source(lines, schema["source"])
        lines.append("    },")
        message_offset += len(schema["messages"])
        field_offset += len(schema["fields"])
    lines.extend([
        "};",
        "inline constexpr std::size_t kProtoSchemaCount =",
        "    sizeof(kProtoSchemas) / sizeof(kProtoSchemas[0]);",
        "",
        "inline constexpr ProtoMessage kProtoMessages[] = {",
    ])
    for schema in schemas:
        for index, name in enumerate(schema["messages"]):
            lines.append("    {%s, %s, %du, %du}," %
                         (cpp_string(schema["name"]), cpp_string(name),
                          schema["fieldStarts"][index],
                          schema["fieldCounts"][index]))
    lines.extend([
        "};",
        "inline constexpr std::size_t kProtoMessageCount =",
        "    sizeof(kProtoMessages) / sizeof(kProtoMessages[0]);",
        "",
        "inline constexpr ProtoField kProtoFields[] = {",
    ])
    for schema in schemas:
        for field in schema["fields"]:
            lines.append(
                "    {%s, %s, %s, %s, %s, %du, %s}," %
                (cpp_string(field["schema"]), cpp_string(field["message"]),
                 cpp_string(field["label"]), cpp_string(field["type"]),
                 cpp_string(field["name"]), field["number"],
                 cpp_string(field["line"])))
    lines.extend([
        "};",
        "inline constexpr std::size_t kProtoFieldCount =",
        "    sizeof(kProtoFields) / sizeof(kProtoFields[0]);",
        "",
        "inline const ProtoSchema* protoSchema(std::string_view name) {",
        "    for (const ProtoSchema& schema : kProtoSchemas)",
        "        if (schema.name == name) return &schema;",
        "    return nullptr;",
        "}",
        "",
        "inline const ProtoMessage* protoMessage(std::string_view schemaName,",
        "                                        std::string_view name) {",
        "    for (const ProtoMessage& message : kProtoMessages)",
        "        if (message.schema == schemaName && message.name == name)",
        "            return &message;",
        "    return nullptr;",
        "}",
        "",
        "inline const ProtoField* protoField(std::string_view name) {",
        "    for (const ProtoField& field : kProtoFields)",
        "        if (field.name == name) return &field;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "ProtoIndex.h")
    schemas = [parse_schema(path) for path in sorted(
        glob.glob(os.path.join(root, "proto", "*.proto")))]
    global_field_offset = 0
    for schema in schemas:
        starts = []
        counts = []
        for name in schema["messages"]:
            rows = [field for field in schema["fields"] if field["message"] == name]
            starts.append(global_field_offset +
                          (schema["fields"].index(rows[0]) if rows else 0))
            counts.append(len(rows))
        schema["fieldStarts"] = starts
        schema["fieldCounts"] = counts
        global_field_offset += len(schema["fields"])
    write_header(header, schemas)
    print("proto schemas=%d messages=%d fields=%d" % (
        len(schemas), sum(len(schema["messages"]) for schema in schemas),
        sum(len(schema["fields"]) for schema in schemas)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
