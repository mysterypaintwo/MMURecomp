#!/usr/bin/env python3
"""Recover the raw pause-menu weapon resource order from MMU.exe.

PauseMenuStatus (vftable 0x696a2c) builds its icon and color rows inline rather
than through the recovered static menu-item supplier pattern. This tool reads
that constructor from docs/state_graph.txt, disassembles it until the first ret
after its last resource push, and records every pushed .rdata path under
`..\\Menus\\Pause\\` whose basename ends in `Icon.xspr` or `Colors.xspr`.

The exact path string, its VA, the push VA, resource order, and the non-reflected
CRC-32 key used by the original asset loader are preserved. No gameplay name,
weapon meaning, or index mapping is inferred.

Usage:
  analyze_pause_weapon_resources.py MMU.exe report.txt header.h
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from analyze_enemy_edge_facts import read
from analyze_game_flow import cstring
from analyze_rtti import PE
from capstone import CS_ARCH_X86, CS_MODE_32, Cs
from crack_hash import mmu_crc32

TOOL = "tools/analyze_pause_weapon_resources.py"
CTOR_RE = re.compile(
    r"^=== PauseMenuStatus vftable=(0x[0-9a-f]+) "
    r"ctor=(0x[0-9a-f]+) ===$", re.MULTILINE)
PAUSE_PREFIX = "..\\Menus\\Pause\\"
SUFFIXES = ("Icon.xspr", "Colors.xspr")
MD = Cs(CS_ARCH_X86, CS_MODE_32)


def constructor_va(text):
    match = CTOR_RE.search(text)
    if not match:
        raise RuntimeError("PauseMenuStatus constructor not found")
    return int(match.group(2), 16)


def resource_pushes(pe, start):
    off = pe.rva_to_off(start - pe.image_base)
    rows = list(MD.disasm(pe.data[off:off + 0x4000], start))
    candidates = []
    for row in rows:
        if row.mnemonic != "push":
            continue
        try:
            va = int(row.op_str, 16)
        except ValueError:
            continue
        if not pe.in_rdata(va - pe.image_base):
            continue
        text = cstring(pe, va, 1, 160)
        if not text.startswith(PAUSE_PREFIX):
            continue
        if not text.endswith(SUFFIXES):
            continue
        candidates.append((row.address, va, text))
    if not candidates:
        raise RuntimeError("no pause resource pushes found")
    last_push = candidates[-1][0]
    end = next((row.address for row in rows
                if row.mnemonic == "ret" and row.address > last_push), None)
    if end is None:
        raise RuntimeError("no ret after last pause resource push")
    return [entry for entry in candidates if entry[0] < end], end


def collect(pe, start):
    pushes, end = resource_pushes(pe, start)
    facts = []
    for sequence, (push_va, string_va, path) in enumerate(pushes):
        facts.append({
            "sequence": sequence,
            "pushVa": push_va,
            "stringVa": string_va,
            "path": path,
            "key": mmu_crc32(path.encode()),
            "kind": "Colors" if path.endswith("Colors.xspr") else "Icon",
        })
    return facts, end


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_report(path, facts, start, end):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by %s\n" % TOOL)
        out.write("PauseMenuStatus constructor 0x%06x..0x%06x; exact pushed "
                  "strings only.\n" % (start, end))
        out.write("resources=%d icons=%d colors=%d\n\n" %
                  (len(facts),
                   sum(f["kind"] == "Icon" for f in facts),
                   sum(f["kind"] == "Colors" for f in facts)))
        for fact in facts:
            out.write("seq=%-2d push=0x%06x string=0x%06x key=0x%08x %-6s %s\n" %
                      (fact["sequence"], fact["pushVa"], fact["stringVa"],
                       fact["key"], fact["kind"], fact["path"]))


def write_header(path, facts, start, end):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from MMU.exe." % TOOL,
        "// Verbatim inline resource order from PauseMenuStatus 0x%06x..0x%06x."
        % (start, end),
        "// Keys are the original non-reflected CRC-32 of the exact path.",
        "struct PauseWeaponResource {",
        "    u16 sequence;",
        "    u32 pushVa;",
        "    u32 stringVa;",
        "    u32 key;",
        "    std::string_view kind;",
        "    std::string_view path;",
        "};",
        "",
        "inline constexpr PauseWeaponResource kPauseWeaponResources[] = {",
    ]
    for fact in facts:
        lines.append("    {%du, 0x%06xu, 0x%06xu, 0x%08xu, %s, %s}," %
                     (fact["sequence"], fact["pushVa"], fact["stringVa"],
                      fact["key"], cpp_string(fact["kind"]),
                      cpp_string(fact["path"])))
    lines.extend([
        "};",
        "",
        "inline const PauseWeaponResource* pauseWeaponResource(u32 key) {",
        "    for (const PauseWeaponResource& resource : kPauseWeaponResources)",
        "        if (resource.key == key) return &resource;",
        "    return nullptr;",
        "}",
        "",
        "inline const PauseWeaponResource* pauseWeaponResource(std::string_view path) {",
        "    for (const PauseWeaponResource& resource : kPauseWeaponResources)",
        "        if (resource.path == path) return &resource;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    exe, report, header = sys.argv[1:]
    root = os.path.dirname(os.path.dirname(report))
    graph = os.path.join(root, "docs", "state_graph.txt")
    pe = PE(open(exe, "rb").read())
    start = constructor_va(read(graph))
    facts, end = collect(pe, start)
    write_report(report, facts, start, end)
    write_header(header, facts, start, end)
    print("resources=%d icons=%d colors=%d" %
          (len(facts),
           sum(f["kind"] == "Icon" for f in facts),
           sum(f["kind"] == "Colors" for f in facts)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
