#!/usr/bin/env python3
"""Recover state names registered through MMU.exe's 0x401370 helper.

Every state registration calls 0x401370 with a std::string holding the state
name.  The Ghidra output drops the argument, so this tool scans .text for
E8 rel32 calls to 0x401370 and takes the last printable .rdata address
referenced in the 0x90 bytes before the call.  That matches the constructor
pattern used by the Telly example at 0x586578 ("MoveH", "MoveV", "Idle").

Outputs a compact evidence report and a generated C++ table of unique names
with their 0x43c010 hashes.  The table is evidence only; it does not assign
behaviour to a name.
"""

import struct
import sys
from collections import Counter

from analyze_game_flow import cstring
from analyze_rtti import PE

REGISTER_STATE = 0x401370
SCAN_BACK = 0x90


def state_hash(name):
    value = 0
    for ch in name.encode("latin1"):
        byte = ch & 0xFF
        for mask in (0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01):
            top = value & 0x80000000
            value = ((value << 1) & 0xFFFFFFFF) | (1 if byte & mask else 0)
            if top:
                value ^= 0x4C11DB7
    return value


def registration_sites(pe):
    data = pe.data
    sites = []
    for name, va, vsize, rawoff, rawsize in pe.sections:
        if name != ".text":
            continue
        base = pe.image_base + va
        for off in range(rawoff, rawoff + rawsize - 5):
            if data[off] != 0xE8:
                continue
            rel = struct.unpack_from("<i", data, off + 1)[0]
            if base + (off - rawoff) + 5 + rel == REGISTER_STATE:
                sites.append(base + (off - rawoff))
    return sites


def name_before(pe, va, span=SCAN_BACK):
    off = pe.rva_to_off(va - pe.image_base)
    if off is None:
        return None
    start = max(0, off - span)
    chunk = pe.data[start:off]
    found = None
    for i in range(len(chunk) - 3):
        candidate = struct.unpack_from("<I", chunk, i)[0]
        if pe.in_rdata(candidate - pe.image_base):
            text = cstring(pe, candidate, 1, 48)
            if text and all(ch.isprintable() for ch in text):
                found = text
    return found


def cpp_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    if len(sys.argv) < 2:
        print("usage: analyze_state_names.py MMU.exe [report.txt] [header.h]")
        return 1
    report_path = sys.argv[2] if len(sys.argv) > 2 else "docs/state_names.txt"
    header_path = sys.argv[3] if len(sys.argv) > 3 else \
        "core/include/mmu/core/RegisteredStateNames.h"

    pe = PE(open(sys.argv[1], "rb").read())
    sites = registration_sites(pe)
    records = []
    unique = []
    for site in sites:
        name = name_before(pe, site)
        if name is None:
            continue
        records.append((site, name, state_hash(name)))
        if name not in unique:
            unique.append(name)

    counts = Counter(name for _, name, _ in records)
    first_site = {}
    for site, name, _ in records:
        first_site.setdefault(name, site)

    with open(report_path, "w") as out:
        out.write("Generated by tools/analyze_state_names.py\n")
        out.write("Source: 0x401370 registration calls in MMU.exe\n")
        out.write("Heuristic: last printable .rdata immediate in the 0x90 bytes "
                  "before a call; string values are evidence, not behaviour.\n")
        out.write(f"registration calls={len(sites)} named={len(records)} "
                  f"unique={len(unique)}\n\n")
        out.write("=== unique registered names (first registration order) ===\n")
        for i, name in enumerate(unique):
            out.write(f"#{i:03d} hash=0x{state_hash(name):08x} "
                      f"first=0x{first_site[name]:x} refs={counts[name]:2d}  {name}\n")
        out.write("\n=== registration call sites ===\n")
        for site, name, hash_value in records:
            out.write(f"0x{site:x}  0x{hash_value:08x}  {name}\n")

    with open(header_path, "w") as out:
        out.write("#pragma once\n\n")
        out.write("#include \"mmu/core/Types.h\"\n\n")
        out.write("#include <cstddef>\n")
        out.write("#include <string_view>\n\n")
        out.write("namespace mmu {\n\n")
        out.write("// Generated by tools/analyze_state_names.py. These are the unique\n")
        out.write(f"// state names registered at 0x401370 ({len(sites)} calls, "
                  f"{len(unique)} unique). No behaviour is inferred.\n")
        out.write("struct RegisteredStateName {\n")
        out.write("    u32 hash;\n")
        out.write("    std::string_view name;\n")
        out.write("};\n\n")
        out.write("inline constexpr RegisteredStateName kRegisteredStateNames[] = {\n")
        for name in unique:
            out.write(f"    {{0x{state_hash(name):08x}u, \"{cpp_string(name)}\"}},\n")
        out.write("};\n\n")
        out.write("inline constexpr std::size_t kRegisteredStateNameCount =\n")
        out.write("    sizeof(kRegisteredStateNames) / sizeof(kRegisteredStateNames[0]);\n\n")
        out.write("inline bool isRegisteredStateName(std::string_view name) {\n")
        out.write("    for (const RegisteredStateName& entry : kRegisteredStateNames)\n")
        out.write("        if (entry.name == name) return true;\n")
        out.write("    return false;\n")
        out.write("}\n\n")
        out.write("} // namespace mmu\n")

    print(f"sites={len(sites)} named={len(records)} unique={len(unique)} "
          f"report={report_path} header={header_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
