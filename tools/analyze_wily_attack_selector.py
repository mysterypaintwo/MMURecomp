#!/usr/bin/env python3
"""Recover WilyMachine's attack-phase selector from raw MMU.exe evidence.

FUN_0056d580 is a four-entry jump table over the raw field this+0x368. Each
entry calls FUN_004405c0 with a literal state name at 0x678fa8..0x678fcc.
Phases 1 and 2 also clear the raw counter at this+0x374; phase 3 writes 0 back
to +0x368, while the other paths fall through to an increment. The only caller
is the Hover update at 0x56da4a, reached when the this+0x364 timer goes below
zero. FUN_0056dca0 is a raw event handler whose 0xf branch selects EnergyFill
for phase 0 and Crush for phase 1.

No gameplay label is assigned to any field, phase value, event code, or state
name beyond the literal strings stored in the executable.

Outputs:
  docs/wily_attack_selector.txt
  core/include/mmu/core/WilyAttackSelector.h
"""

import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_rtti import PE
from analyze_boss_damage import callers, text_range
from capstone import CS_ARCH_X86, CS_MODE_32, Cs

SELECTOR = 0x56D580
JUMP_TABLE = 0x56D644
PHASE_STATE_STRINGS = (0x678FA8, 0x678FB4, 0x678FC0, 0x678FCC)
PHASE_FIELD = 0x368
COUNTER_FIELD = 0x374
TIMER_FIELD = 0x364
HOVER_UPDATE = 0x56DA10
EVENT_HANDLER = 0x56DCA0
EVENT_CODE = 0xF
EVENT_STRINGS = (0x679084, 0x679090)
GOTO3_ENTER = 0x56CB20
GOTO3_UPDATE = 0x56D2B0


def cstring(pe, va):
    off = pe.rva_to_off(va - pe.image_base)
    return pe.data[off:off + 64].split(b"\0", 1)[0].decode("ascii", "replace")


def disasm(pe, start, size=256):
    off = pe.rva_to_off(start - pe.image_base)
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    return list(md.disasm(pe.data[off:off + size], start))


def analyze(exe_path):
    pe = PE(open(exe_path, "rb").read())
    lo, hi = text_range(pe)

    off = pe.rva_to_off(JUMP_TABLE - pe.image_base)
    targets = [struct.unpack_from("<I", pe.data, off + 4 * i)[0]
               for i in range(4)]
    names = [cstring(pe, va) for va in PHASE_STATE_STRINGS]
    if names != ["GotoAttack1", "GotoAttack2", "GotoAttack3", "GotoAttack4"]:
        raise RuntimeError("unexpected selector state strings: %r" % names)

    rows = disasm(pe, SELECTOR, 0xC0)
    clear_phases = []
    wrap_writes = 0
    phase_reads = 0
    for ins in rows:
        text = "%s %s" % (ins.mnemonic, ins.op_str)
        if "0x%x" % COUNTER_FIELD in text and "mov" in ins.mnemonic and \
                text.endswith(", 0"):
            # Attribute the clear to the jump-table target containing it.
            for index, target in enumerate(targets):
                if target <= ins.address < (targets[index + 1] if index < 3 else 0x56D628):
                    if index not in clear_phases:
                        clear_phases.append(index)
        if "0x%x" % PHASE_FIELD in text:
            phase_reads += 1
            if "mov" in ins.mnemonic and text.endswith(", 0"):
                wrap_writes += 1
    if clear_phases != [1, 2]:
        raise RuntimeError("unexpected counter-clear phases: %r" % clear_phases)
    if wrap_writes < 1:
        raise RuntimeError("phase wrap write not found")

    selector_callers = callers(pe, pe.data, lo, hi, SELECTOR)
    if selector_callers != [0x56DA4A]:
        raise RuntimeError("unexpected selector callers: %r" % selector_callers)

    # The raw literal strings used by the 0xf event handler.
    event_names = [cstring(pe, va) for va in EVENT_STRINGS]
    if event_names != ["EnergyFill", "Crush"]:
        raise RuntimeError("unexpected event handler strings: %r" % event_names)

    goto3_enter_rows = [ins for ins in disasm(pe, GOTO3_ENTER, 0xE0)
                        if "0x%x" % COUNTER_FIELD in ins.op_str]
    goto3_update_rows = [ins for ins in disasm(pe, GOTO3_UPDATE, 0x120)
                         if "0x%x" % COUNTER_FIELD in ins.op_str]
    return {
        "targets": targets,
        "names": names,
        "clear_phases": clear_phases,
        "phase_reads": phase_reads,
        "wrap_writes": wrap_writes,
        "selector_callers": selector_callers,
        "event_names": event_names,
        "goto3_enter": goto3_enter_rows,
        "goto3_update": goto3_update_rows,
        "selector_rows": rows,
    }


def write_report(path, facts):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by tools/analyze_wily_attack_selector.py\n")
        out.write("selector=0x%06x jump_table=0x%06x phase=this+0x%x "
                  "counter=this+0x%x timer=this+0x%x\n\n" %
                  (SELECTOR, JUMP_TABLE, PHASE_FIELD, COUNTER_FIELD, TIMER_FIELD))
        out.write("Phase jump table (phase -> target -> literal state name):\n")
        for i, (target, name) in enumerate(zip(facts["targets"], facts["names"])):
            out.write("  %d -> 0x%06x -> \"%s\"%s\n" %
                      (i, target, name,
                       "  (clears this+0x374)" if i in facts["clear_phases"] else ""))
        out.write("Phase 3 writes 0 to this+0x368; other paths fall through to "
                  "the +1 increment at 0x56d628.\n")
        out.write("Selector direct callers: %s\n\n" %
                  ", ".join("0x%x" % va for va in facts["selector_callers"]))
        out.write("Hover update FUN_0056da10 decrements this+0x364 by dt and "
                  "calls the selector when the x87 comparison at 0x56da42 "
                  "falls through (test ah,0x41 / jp).\n\n")
        out.write("FUN_0056dca0 raw event 0xf handler: phase 0 -> \"%s\", "
                  "phase 1 -> \"%s\"; other event codes go to FUN_00575f40.\n\n" %
                  (facts["event_names"][0], facts["event_names"][1]))
        out.write("FUN_0056cb20 (GotoAttack3 enter) and FUN_0056d2b0 "
                  "(GotoAttack3 update) counter accesses:\n")
        for ins in facts["goto3_enter"] + facts["goto3_update"]:
            out.write("  0x%06x %-7s %s\n" % (ins.address, ins.mnemonic, ins.op_str))
        out.write("\nFUN_0056d580 raw selector instructions:\n")
        for ins in facts["selector_rows"]:
            out.write("  0x%06x %-7s %s\n" % (ins.address, ins.mnemonic, ins.op_str))


def write_header(path, facts):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by tools/analyze_wily_attack_selector.py. Raw executable",
        "// constants only; no gameplay label is assigned to a phase or field.",
        "inline constexpr u32 kWilyPhaseField = 0x368u;",
        "inline constexpr u32 kWilyShotCounterField = 0x374u;",
        "inline constexpr u32 kWilyHoverTimerField = 0x364u;",
        "inline constexpr u32 kWilySelectorVa = 0x56d580u;",
        "inline constexpr u32 kWilySelectorJumpTableVa = 0x56d644u;",
        "inline constexpr u32 kWilySelectorCallerVa = 0x56da4au;",
        "inline constexpr u32 kWilyEventCode0f = 0xfu;",
        "inline constexpr int kWilyPhaseCount = 4;",
        "inline constexpr int kWilyWrapPhase = 3;",
        "inline constexpr int kWilyShotCounterLimit = 3;",
        "",
        "struct WilySelectorPhase {",
        "    std::string_view stateName;",
        "    u32 targetVa;",
        "    bool clearsShotCounter;",
        "};",
        "",
        "inline constexpr WilySelectorPhase kWilySelectorPhases[] = {",
    ]
    for i, (name, target) in enumerate(zip(facts["names"], facts["targets"])):
        lines.append("    {\"%s\", 0x%06xu, %s}," %
                     (name, target, "true" if i in facts["clear_phases"] else "false"))
    lines.extend([
        "};",
        "",
        "constexpr int wilySelectorPhase(int phase) {",
        "    return ((phase % kWilyPhaseCount) + kWilyPhaseCount) % kWilyPhaseCount;",
        "}",
        "",
        "constexpr bool wilySelectorClearsShotCounter(int phase) {",
        "    return kWilySelectorPhases[wilySelectorPhase(phase)].clearsShotCounter;",
        "}",
        "",
        "constexpr std::string_view wilySelectorPhaseState(int phase) {",
        "    return kWilySelectorPhases[wilySelectorPhase(phase)].stateName;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    exe, report, header = sys.argv[1:]
    facts = analyze(exe)
    write_report(report, facts)
    write_header(header, facts)
    print("phases=%d clear=%s callers=%d" %
          (len(facts["names"]),
           ",".join(str(p) for p in facts["clear_phases"]),
           len(facts["selector_callers"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
