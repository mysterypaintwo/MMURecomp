#!/usr/bin/env python3
"""Map cutscenedefs.mmu database keys to original .xcut path strings.

The protobuf Database stores 80 cutscenes and 80 uint32 keys. The binary also
contains the 80 legacy `..\\Cutscenes\\...xcut` paths, hashed with the same
non-reflected CRC-32 used by the named-state dispatcher. Matching hashes gives
a stable key -> scene-name table without a protobuf runtime in shipped code.

Outputs:
  docs/cutscene_keys.txt
  core/include/mmu/core/RegisteredCutscenes.h
"""

import os
import re
import struct
import sys

from analyze_rtti import PE
from analyze_state_names import state_hash


def read_varint(data, off):
    value = 0
    shift = 0
    while True:
        if off >= len(data):
            raise ValueError('truncated varint')
        byte = data[off]
        off += 1
        value |= (byte & 0x7F) << shift
        if not (byte & 0x80):
            return value, off
        shift += 7
        if shift > 63:
            raise ValueError('varint too long')


def database_keys(data):
    off = 0
    keys = []
    while off < len(data):
        tag, off = read_varint(data, off)
        number = tag >> 3
        wire = tag & 7
        if wire == 0:
            value, off = read_varint(data, off)
            if number == 2:
                keys.append(value & 0xFFFFFFFF)
        elif wire == 2:
            length, off = read_varint(data, off)
            off += length
        elif wire == 5:
            off += 4
        elif wire == 1:
            off += 8
        else:
            raise ValueError('unsupported wire type %d' % wire)
        if off > len(data):
            raise ValueError('truncated field')
    return keys


def xcut_paths(pe):
    found = {}
    for match in re.finditer(rb'[ -~]{8,}', pe.data):
        run = match.group().decode('latin1')
        lower = run.lower()
        index = lower.find('.xcut')
        if index < 0:
            continue
        path = run[:index + 5]
        prefix = re.search(r'(?:\.\.\\|[A-Za-z]:\\)', path)
        if prefix:
            path = path[prefix.start():]
        found[state_hash(path)] = path
    return found


def cpp_string(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


def main(argv):
    if len(argv) != 3:
        print('usage: analyze_cutscene_keys.py MMU.exe cutscenedefs.mmu', file=sys.stderr)
        return 2

    with open(argv[1], 'rb') as stream:
        pe = PE(stream.read())
    with open(argv[2], 'rb') as stream:
        keys = database_keys(stream.read())

    paths = xcut_paths(pe)
    rows = []
    unmatched = []
    for key in keys:
        path = paths.get(key)
        if path is None:
            unmatched.append(key)
            continue
        rows.append((key, path))

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = os.path.join(root, 'docs', 'cutscene_keys.txt')
    header = os.path.join(root, 'core', 'include', 'mmu', 'core',
                          'RegisteredCutscenes.h')
    with open(report, 'w') as out:
        out.write('Generated by tools/analyze_cutscene_keys.py\n')
        out.write('cutscene keys=%d matched=%d unmatched=%d\n' %
                  (len(keys), len(rows), len(unmatched)))
        for index, (key, path) in enumerate(rows):
            out.write('%2d key=%-10u hash=0x%08x %s\n' %
                      (index, key, key, path))
        for key in unmatched:
            out.write('UNMATCHED key=%u\n' % key)

    with open(header, 'w') as out:
        out.write('#pragma once\n\n')
        out.write('#include "mmu/core/Types.h"\n\n')
        out.write('#include <cstddef>\n')
        out.write('#include <string_view>\n\n')
        out.write('namespace mmu {\n\n')
        out.write('// Generated by tools/analyze_cutscene_keys.py. Database keys\n')
        out.write('// are hashes of the original .xcut path strings. Evidence only.\n')
        out.write('struct RegisteredCutscene {\n')
        out.write('    u32 key;\n')
        out.write('    std::string_view path;\n')
        out.write('};\n\n')
        out.write('inline constexpr RegisteredCutscene kRegisteredCutscenes[] = {\n')
        for key, path in rows:
            out.write('    {%uu, "%s"},\n' % (key, cpp_string(path)))
        out.write('};\n\n')
        out.write('inline constexpr std::size_t kRegisteredCutsceneCount =\n')
        out.write('    sizeof(kRegisteredCutscenes) / sizeof(kRegisteredCutscenes[0]);\n\n')
        out.write('inline std::string_view cutscenePathForKey(u32 key) {\n')
        out.write('    for (const RegisteredCutscene& row : kRegisteredCutscenes)\n')
        out.write('        if (row.key == key) return row.path;\n')
        out.write('    return {};\n')
        out.write('}\n\n')
        out.write('} // namespace mmu\n')

    print('keys=%d matched=%d unmatched=%d report=%s header=%s' %
          (len(keys), len(rows), len(unmatched), report, header))
    return 0 if not unmatched else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv))
