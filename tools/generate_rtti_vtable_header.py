#!/usr/bin/env python3
"""Derive a compact C++ RTTI/vtable table from docs/vtables.txt.

docs/vtables.txt is generated by tools/analyze_rtti.py directly from MMU.exe.
This tool copies its exact mangled names, vftable VAs and virtual-function
slots into a portable header. The demangled `className` is only the raw
`.?AV...@@` wrapper removed; template encodings such as `?$Foo@$00` are kept
verbatim. No slot is assigned a name or gameplay meaning.

Usage:
  generate_rtti_vtable_header.py [report.txt] [header.h]
"""

import os
import re
import sys

HEADER_RE = re.compile(
    r"^image base 0x[0-9a-f]+, type descriptors=(\d+), COLs=(\d+), vtables=(\d+)$")
ROW_RE = re.compile(
    r"^(\S+)\s+vftable RVA 0x[0-9a-f]+ \(VA (0x[0-9a-f]+)\)$")
TOOL = "tools/generate_rtti_vtable_header.py"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path):
    lines = open(path, "r", encoding="latin1").read().splitlines()
    counts = None
    tables = []
    slots = []
    i = 0
    while i < len(lines):
        match = HEADER_RE.match(lines[i])
        if match:
            counts = tuple(int(part) for part in match.groups())
            i += 1
            continue
        match = ROW_RE.match(lines[i])
        if match:
            mangled, va = match.groups()
            table_slots = []
            i += 1
            while i < len(lines) and lines[i].startswith("  "):
                table_slots.extend(int(part, 16) for part in lines[i].split())
                i += 1
            class_name = mangled[4:-2] if mangled.startswith(".?AV") and mangled.endswith("@@") else mangled
            tables.append({
                "mangled": mangled,
                "class": class_name,
                "va": int(va, 16),
                "slotOffset": len(slots),
                "slotCount": len(table_slots),
            })
            slots.extend(table_slots)
            continue
        i += 1
    if counts is None or counts[2] != len(tables):
        raise RuntimeError("RTTI report table count mismatch")
    return counts, tables, slots


def write_header(path, counts, tables, slots):
    lines = [
        "#pragma once",
        "",
        '#include "mmu/core/Types.h"',
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/vtables.txt." % TOOL,
        "// Mangled RTTI names, vftable VAs and function pointers are copied",
        "// verbatim from tools/analyze_rtti.py. Slot indices are not semantics.",
        "inline constexpr u32 kRttiTypeDescriptorCount = %du;" % counts[0],
        "inline constexpr u32 kRttiCompleteObjectLocatorCount = %du;" % counts[1],
        "",
        "struct RttiVtable {",
        "    std::string_view mangledName;",
        "    std::string_view className;",
        "    u32 vftableVa;",
        "    u32 slotOffset;",
        "    u16 slotCount;",
        "};",
        "",
        "inline constexpr RttiVtable kRttiVtables[] = {",
    ]
    for table in tables:
        lines.append(
            "    {%s, %s, 0x%06xu, %du, %du}," %
            (cpp_string(table["mangled"]), cpp_string(table["class"]),
             table["va"], table["slotOffset"], table["slotCount"]))
    lines.extend([
        "};",
        "",
        "inline constexpr u32 kRttiVtableSlots[] = {",
    ])
    for i in range(0, len(slots), 8):
        lines.append("    " + " ".join("0x%06xu," % slot for slot in slots[i:i + 8]))
    lines.extend([
        "};",
        "",
        "inline constexpr std::size_t kRttiVtableCount =",
        "    sizeof(kRttiVtables) / sizeof(kRttiVtables[0]);",
        "inline constexpr std::size_t kRttiVtableSlotCount =",
        "    sizeof(kRttiVtableSlots) / sizeof(kRttiVtableSlots[0]);",
        "",
        "inline const RttiVtable* rttiVtable(std::string_view className) {",
        "    for (const RttiVtable& table : kRttiVtables)",
        "        if (table.className == className) return &table;",
        "    return nullptr;",
        "}",
        "",
        "inline const RttiVtable* rttiVtableByVa(u32 vftableVa) {",
        "    for (const RttiVtable& table : kRttiVtables)",
        "        if (table.vftableVa == vftableVa) return &table;",
        "    return nullptr;",
        "}",
        "",
        "inline u32 rttiVtableSlot(const RttiVtable& table, u32 index) {",
        "    return index < table.slotCount ? kRttiVtableSlots[table.slotOffset + index] : 0u;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "docs", "vtables.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "RttiVtables.h")
    counts, tables, slots = parse(report)
    write_header(header, counts, tables, slots)
    print("rtti vtables=%d slots=%d" % (len(tables), len(slots)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
