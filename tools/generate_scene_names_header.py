#!/usr/bin/env python3
"""Derive a portable scene-path table from tools/scene_names.inc.

tools/scene_names.inc is generated by tools/extract_metadata.py directly from
MMU.exe. This tool copies its exact C++ string literals and their order into a
header the SDL2 harness can query without reading the source tree at runtime.
The literals are not decoded, renamed, or matched to runtime scene keys here.

Usage:
  generate_scene_names_header.py [inc] [header.h]
"""

import os
import re
import sys

ROW_RE = re.compile(r'^\s*("(?:\\.|[^"\\])*")\,?\s*$')
TOOL = "tools/generate_scene_names_header.py"


def parse(path):
    rows = []
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = ROW_RE.match(line.rstrip("\r\n"))
            if match:
                rows.append(match.group(1))
    return rows


def write_header(path, rows):
    lines = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from tools/scene_names.inc." % TOOL,
        "// Exact editor-side .xscn string literals and their original order are",
        "// copied verbatim. No runtime key or gameplay role is inferred here.",
        "inline constexpr std::string_view kSceneNames[] = {",
    ]
    for row in rows:
        lines.append("    %s," % row)
    lines.extend([
        "};",
        "",
        "inline constexpr std::size_t kSceneNameCount =",
        "    sizeof(kSceneNames) / sizeof(kSceneNames[0]);",
        "",
        "inline std::string_view sceneName(std::size_t index) {",
        "    return index < kSceneNameCount ? kSceneNames[index] : std::string_view();",
        "}",
        "",
        "inline std::size_t sceneNameIndex(std::string_view name) {",
        "    for (std::size_t i = 0; i < kSceneNameCount; ++i)",
        "        if (kSceneNames[i] == name) return i;",
        "    return kSceneNameCount;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "tools", "scene_names.inc")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "SceneNames.h")
    rows = parse(source)
    write_header(header, rows)
    print("scene names=%d" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
