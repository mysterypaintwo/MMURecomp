#!/usr/bin/env python3
"""Recover the global manager's boot state from MMU.exe.

FUN_0050bbb0 is the constructor for the manager object stored at 0x6c55a0
(caller 0x5df886). It zeroes the manager, sets the initial activity mask to
0x80, starts the CSN00Logos cutscene with FUN_0050ba40, stores the CSN01Intro
path with FUN_004308c0, then writes +0x08 = 0x80, +0x0c = 4 and +0x30 = 1.
The last field is the activity mask source that 0x507ec0 reads, so this closes
the previously unresolved "all masks active" shortcut in the state runtime.

Outputs:
  docs/boot_cutscenes.txt
  core/include/mmu/core/BootCutsceneTable.h
"""

import os
import sys

from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_OP_REG

from analyze_completion_cutscenes import PE, disasm_function, immediate_of, read_c_string

CONSTRUCTOR_VA = 0x50BBB0
PLAY_CALL_VA = 0x50BA40
PENDING_CALL_VA = 0x4308C0
CALLER_VA = 0x5DF886
MANAGER_GLOBAL_VA = 0x6C55A0


def find_call(insns, va):
    for i, ins in enumerate(insns):
        if ins.mnemonic == "call" and immediate_of(ins) == va:
            return i
    raise RuntimeError("no call to 0x%x in boot constructor" % va)


def literal_before(insns, index, count=16):
    for ins in reversed(insns[max(0, index - count):index]):
        if ins.mnemonic != "push":
            continue
        va = immediate_of(ins)
        if va is not None and read_c_string(PE_INSTANCE, va) is not None:
            return va
    raise RuntimeError("no literal path before call at 0x%x" %
                       insns[index].address)


def dword_writes(insns, first, last):
    """Dword writes through the manager pointer saved at [ebp - 0x48]."""
    result = {}
    manager_regs = set()
    for ins in insns[first:last]:
        if ins.mnemonic == "mov" and len(ins.operands) == 2:
            dst, src = ins.operands
            if (dst.type == X86_OP_REG and src.type == X86_OP_MEM and
                    src.mem.base != 0 and src.mem.disp == -0x48):
                manager_regs.add(ins.reg_name(dst.reg))
            elif dst.type == X86_OP_REG:
                manager_regs.discard(ins.reg_name(dst.reg))
            if (dst.type == X86_OP_MEM and src.type == X86_OP_IMM and
                    dst.mem.base != 0 and dst.mem.index == 0 and
                    ins.reg_name(dst.mem.base) in manager_regs):
                result[dst.mem.disp & 0xffffffff] = src.imm
        elif ins.mnemonic == "lea" and ins.operands and \
                ins.operands[0].type == X86_OP_REG:
            manager_regs.discard(ins.reg_name(ins.operands[0].reg))
    return result


def collect(pe, insns):
    global PE_INSTANCE
    PE_INSTANCE = pe

    play_index = find_call(insns, PLAY_CALL_VA)
    pending_index = find_call(insns, PENDING_CALL_VA)
    play_literal = literal_before(insns, play_index)
    pending_literal = literal_before(insns, pending_index)

    # The initial mask is the final dword write to offset 0 before the first
    # cutscene literal is pushed.
    initial_writes = dword_writes(insns, 0, play_index)
    if initial_writes.get(0) != 0x80:
        raise RuntimeError("unexpected boot activity mask: %s" %
                           hex(initial_writes.get(0, 0)))

    final_writes = dword_writes(insns, play_index, len(insns))
    expected = {0x08: 0x80, 0x0C: 0x04, 0x30: 0x01}
    for offset, value in expected.items():
        if final_writes.get(offset) != value:
            raise RuntimeError("boot write +0x%02x: expected 0x%x, got %s" %
                               (offset, value, hex(final_writes.get(offset, 0))))

    return {
        "constructorVa": CONSTRUCTOR_VA,
        "callerVa": CALLER_VA,
        "managerGlobalVa": MANAGER_GLOBAL_VA,
        "initialMask": initial_writes[0],
        "playPathVa": play_literal,
        "playPath": read_c_string(pe, play_literal),
        "pendingPathVa": pending_literal,
        "pendingPath": read_c_string(pe, pending_literal),
        "writes": tuple(sorted(expected.items())),
    }


def write_report(row, path):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by tools/analyze_boot_cutscenes.py\n")
        out.write("Source: FUN_0050bbb0, the only caller of which constructs the\n")
        out.write("global manager at 0x6c55a0 (call site 0x5df886).\n")
        out.write("initial activity mask=0x%x\n" % row["initialMask"])
        out.write("immediate path=0x%06x %s\n" %
                  (row["playPathVa"], row["playPath"]))
        out.write("pending path  =0x%06x %s\n" %
                  (row["pendingPathVa"], row["pendingPath"]))
        for offset, value in row["writes"]:
            out.write("manager write +0x%02x = 0x%x\n" % (offset, value))


def write_header(row, path):
    with open(path, "w", encoding="utf-8") as out:
        out.write("#pragma once\n\n")
        out.write("#include \"mmu/core/Types.h\"\n\n")
        out.write("#include <string_view>\n\n")
        out.write("namespace mmu {\n\n")
        out.write("// Generated by tools/analyze_boot_cutscenes.py.\n")
        out.write("// The manager constructor FUN_0050bbb0 starts one cutscene\n")
        out.write("// immediately and stores another for later playback.\n")
        out.write("inline constexpr u32 kBootActivityMask = 0x%03xu;\n" %
                  row["initialMask"])
        out.write("inline constexpr std::string_view kBootPlayCutscene =\n")
        out.write("    \"%s\";\n" % row["playPath"].replace("\\", "\\\\"))
        out.write("inline constexpr std::string_view kBootPendingCutscene =\n")
        out.write("    \"%s\";\n" % row["pendingPath"].replace("\\", "\\\\"))
        out.write("inline constexpr u32 kBootManagerGlobalVa = 0x%06xu;\n" %
                  row["managerGlobalVa"])
        out.write("inline constexpr u32 kBootConstructorVa = 0x%06xu;\n" %
                  row["constructorVa"])
        out.write("struct BootManagerWrite { u8 offset; u32 value; };\n")
        out.write("inline constexpr BootManagerWrite kBootManagerWrites[] = {\n")
        for offset, value in row["writes"]:
            out.write("    {0x%02xu, 0x%04xu},\n" % (offset, value))
        out.write("};\n")
        out.write("inline constexpr std::size_t kBootManagerWriteCount =\n")
        out.write("    sizeof(kBootManagerWrites) / sizeof(kBootManagerWrites[0]);\n")
        out.write("} // namespace mmu\n")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "docs", "boot_cutscenes.txt")
    header = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        root, "core", "include", "mmu", "core", "BootCutsceneTable.h")
    pe = PE(open(sys.argv[1], "rb").read())
    row = collect(pe, disasm_function(pe, CONSTRUCTOR_VA))
    write_report(row, report)
    write_header(row, header)
    print("report=%s header=%s" % (report, header))
    return 0


if __name__ == "__main__":
    sys.exit(main())
