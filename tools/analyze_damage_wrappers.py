#!/usr/bin/env python3
"""Recover callers of the two generic boss-meter result wrappers.

FUN_00420380 and FUN_00420690 are called directly by enemy handlers and also
by two shared wrappers (FUN_00420450 / FUN_00420570). This tool scans those
wrapper functions' call sites and applies the same raw owner resolution used by
tools/analyze_boss_damage.py: a known vftable store first, then a unique RTTI
vftable membership. Unresolved rows are kept with empty owner/resolution; no
owner is guessed from a shared base-class handler.

Output:
  docs/damage_wrappers.txt
  core/include/mmu/core/DamageWrapperTable.h
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from analyze_boss_damage import (MEM_RE, PE, callers, caller_facts,
                                 disasm_function, enclosing_prologue,
                                 key_sites, load_vtables, text_range,
                                 vftable_index)

def helper_meter(pe, data, start):
    meter = None
    for _va, mnemonic, operands in disasm_function(pe, data, start):
        if mnemonic == "cmp" and "ebp" not in operands:
            for match in MEM_RE.finditer(operands):
                meter = int(match.group(1), 16)
        if mnemonic == "mov" and operands.startswith("eax, dword ptr ["):
            for match in MEM_RE.finditer(operands):
                meter = int(match.group(1), 16)
    return meter


def result_bits(codes):
    bits = 0
    for code in codes:
        if 0 <= code < 32:
            bits |= 1 << code
    return bits


def analyze(exe_path, root):
    data = open(exe_path, "rb").read()
    pe = PE(data)
    lo, hi = text_range(pe)
    vtables = load_vtables(root)
    vft_index = vftable_index(pe)

    helpers = []
    for site in key_sites(pe, data, lo, hi):
        start = enclosing_prologue(pe, data, site)
        helpers.append({
            "start": start,
            "meter": helper_meter(pe, data, start),
        })

    wrappers = []
    seen = set()
    for helper in helpers:
        for call_va in callers(pe, data, lo, hi, helper["start"]):
            direct = caller_facts(pe, data, lo, vtables, vft_index, call_va)
            # A resolved owner here is a normal enemy handler. An unresolved
            # owner is the shared wrapper that forwards into this helper.
            if direct["owner"] or direct["resolution"]:
                continue
            wrapper_va = direct["handler"]
            if wrapper_va in seen:
                continue
            seen.add(wrapper_va)
            rows = [caller_facts(pe, data, lo, vtables, vft_index, va)
                    for va in callers(pe, data, lo, hi, wrapper_va)]
            wrappers.append(dict(helper, helperVa=helper["start"],
                                 start=wrapper_va, callers=rows))
    if not wrappers:
        raise RuntimeError("no generic damage wrappers found")
    return wrappers


def write_report(path, wrappers):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by tools/analyze_damage_wrappers.py\n")
        out.write("Raw call sites into the generic wrappers that forward to "
                  "the two boss-meter helpers.\n")
        out.write("Owners use the analyze_boss_damage rules; empty owner means "
                  "a shared base handler.\n")
        out.write("wrappers=%d calls=%d resolved=%d\n\n" % (
            len(wrappers),
            sum(len(w["callers"]) for w in wrappers),
            sum(1 for w in wrappers for f in w["callers"] if f["owner"])))
        for wrapper in wrappers:
            out.write("FUN_0x%06x helper=0x%06x meter=0x%x calls=%d\n" % (
                wrapper["start"], wrapper["helperVa"],
                wrapper["meter"] if wrapper["meter"] is not None else 0,
                len(wrapper["callers"])))
            for fact in wrapper["callers"]:
                out.write("  0x%06x -> handler=0x%06x owner=%-18s "
                          "vft=%s slot=%-4s source=%-21s codes=%s\n" % (
                              fact["va"], fact["handler"],
                              fact["owner"] or "-",
                              ("0x%06x" % fact["vft"]) if fact["vft"] else "-",
                              fact["vtableSlot"] if fact["vtableSlot"] is not None
                              else "-",
                              fact["resolution"] or "-",
                              ",".join(str(c) for c in fact["codes"]) or "-"))
            out.write("\n")


def write_header(path, wrappers):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by tools/analyze_damage_wrappers.py from MMU.exe.",
        "// Raw call sites into the shared wrappers FUN_00420450/0x420570.",
        "// Empty owner means a shared base handler; no owner is guessed.",
        "struct DamageWrapperCaller {",
        "    std::string_view owner;",
        "    u32 callVa;",
        "    u32 wrapperVa;",
        "    u32 handlerVa;",
        "    u32 vftableVa;",
        "    u16 vtableSlot;",
        "    u32 resultCodeBits;",
        "    std::string_view resolution;",
        "};",
        "",
    ]
    for index, wrapper in enumerate(wrappers):
        lines.append("inline constexpr u32 kDamageWrapperVa%d = 0x%06x;" %
                     (index, wrapper["start"]))
        lines.append("inline constexpr u32 kDamageWrapperHelperVa%d = 0x%06x;" %
                     (index, wrapper["helperVa"]))
        if wrapper["meter"] is not None:
            lines.append("inline constexpr u32 kDamageWrapperMeter%d = 0x%x;" %
                         (index, wrapper["meter"]))
    lines.extend([
        "",
        "inline constexpr DamageWrapperCaller kDamageWrapperCallers[] = {",
    ])
    for wrapper in wrappers:
        for fact in wrapper["callers"]:
            lines.append(
                "    {\"%s\", 0x%06xu, 0x%06xu, 0x%06xu, 0x%06xu, %du, "
                "0x%08xu, \"%s\"}," %
                (fact["owner"], fact["va"], wrapper["start"],
                 fact["handler"], fact["vft"] or 0,
                 fact["vtableSlot"] or 0, result_bits(fact["codes"]),
                 fact["resolution"]))
    lines.extend([
        "};",
        "",
        "inline constexpr std::size_t kDamageWrapperCallerCount =",
        "    sizeof(kDamageWrapperCallers) / sizeof(kDamageWrapperCallers[0]);",
        "",
        "inline const DamageWrapperCaller* damageWrapperCaller(",
        "        std::string_view owner) {",
        "    for (const DamageWrapperCaller& row : kDamageWrapperCallers)",
        "        if (!row.owner.empty() && row.owner == owner) return &row;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    if len(sys.argv) != 5:
        print(__doc__)
        return 2
    exe, root, report, header = sys.argv[1:]
    wrappers = analyze(exe, root)
    write_report(report, wrappers)
    write_header(header, wrappers)
    print("wrappers=%d callers=%d resolved=%d" % (
        len(wrappers),
        sum(len(w["callers"]) for w in wrappers),
        sum(1 for w in wrappers for f in w["callers"] if f["owner"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
