#!/usr/bin/env python3
"""Recover raw branch facts for the joined enemy state-machine edges.

For each setter/cue edge recorded in docs/enemy_state_machines.txt this tool
disassembles the owning virtual callback from its entry to the call site and
records, verbatim:

  * comparison/test instructions before the call,
  * register/base-pointer memory operands,
  * referenced qword constant addresses and their raw double values,
  * the .rdata key pushed immediately before a setState call, resolved to a
    printable string when possible.

Nothing here assigns a trigger, timing, gameplay meaning or field name. The
output is an evidence table that can be queried alongside EnemyStateGraph.h.

Usage:
  analyze_enemy_edge_facts.py MMU.exe report.txt header.h
"""

import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from analyze_game_flow import cstring
from analyze_rtti import PE
from capstone import CS_ARCH_X86, CS_MODE_32, Cs

MD = Cs(CS_ARCH_X86, CS_MODE_32)
SECTION_RE = re.compile(r"^=== (\S+) vftable=(0x[0-9a-f]+) "
                        r"ctor=(0x[0-9a-f]+) ===$")
EDGE_RE = re.compile(
    r"^  slot (\d+)\s+func=(0x[0-9a-f]+)\s+call=(0x[0-9a-f]+)\s+"
    r"(setState|cue)\s+hash=(0x[0-9a-f]+)\s+(.+?)\s+owner=(\S+)$")
COMPARE_MNEMONICS = {"cmp", "test", "fcom", "fcomp", "fcompp"}
MEM_OPERAND_RE = re.compile(
    r"\[(?:eax|ecx|edx|ebx|esi|edi|ebp|esp) [+-] 0x[0-9a-f]+\]")
QWORD_RE = re.compile(r"qword ptr \[(0x[0-9a-f]+)\]")
PUSH_IMMEDIATE_RE = re.compile(r"0x([0-9a-f]+)")


def read(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def parse_edges(text):
    class_name = ""
    edges = []
    for line in text.splitlines():
        header = SECTION_RE.fullmatch(line)
        if header:
            class_name = header.group(1)
            continue
        match = EDGE_RE.fullmatch(line)
        if not match:
            continue
        slot, func, call, kind, target_hash, target, owner = match.groups()
        edges.append({
            "class": class_name,
            "slot": int(slot),
            "func": int(func, 16),
            "call": int(call, 16),
            "isCue": kind == "cue",
            "hash": int(target_hash, 16),
            "target": target,
            "owner": owner,
        })
    return edges


def rdata_key(pe, rows, call_va):
    """Last printable .rdata immediate pushed in the eight rows before call."""
    found_va = 0
    found_text = ""
    before = [row for row in rows if row.address < call_va][-8:]
    for row in before:
        if row.mnemonic != "push":
            continue
        match = PUSH_IMMEDIATE_RE.fullmatch(row.op_str)
        if not match:
            continue
        va = int(match.group(1), 16)
        if not pe.in_rdata(va - pe.image_base):
            continue
        text = cstring(pe, va, 1, 48)
        if text and all(ch.isprintable() for ch in text):
            found_va, found_text = va, text
    return found_va, found_text


def collect(pe, edges):
    facts = []
    for edge in edges:
        off = pe.rva_to_off(edge["func"] - pe.image_base)
        if off is None:
            raise RuntimeError("function 0x%x outside image" % edge["func"])
        span = edge["call"] - edge["func"] + 16
        rows = list(MD.disasm(pe.data[off:off + span], edge["func"]))
        comparisons = []
        memory = []
        constants = []
        for row in rows:
            if row.address >= edge["call"] + 8:
                break
            if row.mnemonic in COMPARE_MNEMONICS:
                comparisons.append((row.address, row.mnemonic, row.op_str))
            for match in MEM_OPERAND_RE.finditer(row.op_str):
                if match.group(0) not in memory:
                    memory.append(match.group(0))
            for match in QWORD_RE.finditer(row.op_str):
                va = int(match.group(1), 16)
                coff = pe.rva_to_off(va - pe.image_base)
                if coff is None:
                    continue
                value = struct.unpack_from("<d", pe.data, coff)[0]
                if not any(entry[0] == va for entry in constants):
                    constants.append((va, value))
        key_va, key_text = rdata_key(pe, rows, edge["call"])
        facts.append(dict(edge, comparisons=comparisons, memory=memory,
                          constants=constants, keyVa=key_va, key=key_text))
    return facts


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_report(path, facts, tool="tools/analyze_enemy_edge_facts.py"):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by %s\n" % tool)
        out.write("Verbatim branch operands from MMU.exe. No trigger, timing, "
                  "field name or gameplay meaning is assigned.\n")
        out.write("edges=%d comparisons=%d constants=%d\n\n" %
                  (len(facts),
                   sum(len(f["comparisons"]) for f in facts),
                   sum(len(f["constants"]) for f in facts)))
        for fact in facts:
            out.write("=== %s slot=%d func=0x%06x call=0x%06x %s -> %s "
                      "owner=%s ===\n" %
                      (fact["class"], fact["slot"], fact["func"],
                       fact["call"], "cue" if fact["isCue"] else "setState",
                       fact["target"], fact["owner"]))
            out.write("  key=0x%06x %s\n" %
                      (fact["keyVa"], fact["key"] or "(none)"))
            for va, mnemonic, operands in fact["comparisons"]:
                out.write("  0x%06x %-6s %s\n" % (va, mnemonic, operands))
            out.write("  memory: %s\n" %
                      (" ".join(fact["memory"]) or "(none)"))
            for va, value in fact["constants"]:
                out.write("  qword 0x%06x = %r\n" % (va, value))
            out.write("\n")


def write_header(path, facts, prefix="EnemyEdge",
                 tool="tools/analyze_enemy_edge_facts.py"):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from MMU.exe." % tool,
        "// Verbatim operands only; no trigger, timing, field name or meaning.",
        "struct EnemyEdgeComparison {",
        "    u32 instructionVa;",
        "    std::string_view mnemonic;",
        "    std::string_view operands;",
        "};",
        "",
        "struct EnemyEdgeConstant {",
        "    u32 address;",
        "    double value;",
        "};",
        "",
        "struct EnemyEdgeFact {",
        "    std::string_view className;",
        "    u16 vtableSlot;",
        "    u32 functionVa;",
        "    u32 callVa;",
        "    bool isCue;",
        "    u32 targetHash;",
        "    std::string_view targetName;",
        "    std::string_view ownerState;",
        "    u32 setStateKeyVa;",
        "    std::string_view setStateKey;",
        "    const EnemyEdgeComparison* comparisons;",
        "    u16 comparisonCount;",
        "    const std::string_view* memoryOperands;",
        "    u16 memoryOperandCount;",
        "    const EnemyEdgeConstant* constants;",
        "    u16 constantCount;",
        "};",
        "",
    ]
    for index, fact in enumerate(facts):
        ident = "kEnemyEdgeFact_%02d" % index
        if fact["comparisons"]:
            lines.append("inline constexpr EnemyEdgeComparison %s_Comparisons[] = {" %
                         ident)
            for va, mnemonic, operands in fact["comparisons"]:
                lines.append("    {0x%06xu, %s, %s}," %
                             (va, cpp_string(mnemonic), cpp_string(operands)))
            lines.append("};")
        if fact["memory"]:
            lines.append("inline constexpr std::string_view %s_Memory[] = {" %
                         ident)
            lines.extend("    %s," % cpp_string(item) for item in fact["memory"])
            lines.append("};")
        if fact["constants"]:
            lines.append("inline constexpr EnemyEdgeConstant %s_Constants[] = {" %
                         ident)
            for va, value in fact["constants"]:
                lines.append("    {0x%06xu, %r}," % (va, float(value)))
            lines.append("};")
        lines.append("")

    lines.extend([
        "inline constexpr EnemyEdgeFact kEnemyEdgeFacts[] = {",
    ])
    for index, fact in enumerate(facts):
        ident = "kEnemyEdgeFact_%02d" % index
        comparisons = "%s_Comparisons" % ident if fact["comparisons"] else "nullptr"
        memory = "%s_Memory" % ident if fact["memory"] else "nullptr"
        constants = "%s_Constants" % ident if fact["constants"] else "nullptr"
        lines.append(
            "    {%s, %du, 0x%06xu, 0x%06xu, %s, 0x%08xu, %s, %s, "
            "0x%06xu, %s, %s, %du, %s, %du, %s, %du}," %
            (cpp_string(fact["class"]), fact["slot"], fact["func"],
             fact["call"], "true" if fact["isCue"] else "false",
             fact["hash"], cpp_string(fact["target"]),
             cpp_string(fact["owner"]), fact["keyVa"],
             cpp_string(fact["key"]), comparisons,
             len(fact["comparisons"]), memory, len(fact["memory"]),
             constants, len(fact["constants"])))
    lines.extend([
        "};",
        "",
        "inline const EnemyEdgeFact* enemyEdgeFact(std::string_view className,",
        "        u16 slot, u32 callVa) {",
        "    for (const EnemyEdgeFact& fact : kEnemyEdgeFacts)",
        "        if (fact.className == className && fact.vtableSlot == slot &&",
        "            fact.callVa == callVa) return &fact;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    text = "\n".join(lines)
    if prefix != "EnemyEdge":
        text = text.replace("EnemyEdge", prefix)
        text = text.replace("enemyEdgeFact",
                            prefix[0].lower() + prefix[1:] + "Fact")
    with open(path, "w", encoding="utf-8") as out:
        out.write(text)


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    exe, report, header = sys.argv[1:]
    root = os.path.dirname(os.path.dirname(report))
    graph = os.path.join(root, "docs", "enemy_state_machines.txt")
    pe = PE(open(exe, "rb").read())
    facts = collect(pe, parse_edges(read(graph)))
    write_report(report, facts)
    write_header(header, facts)
    print("edges=%d comparisons=%d constants=%d" %
          (len(facts),
           sum(len(f["comparisons"]) for f in facts),
           sum(len(f["constants"]) for f in facts)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
