#!/usr/bin/env python3
"""Derive only the counters from docs/key_names_discovered.txt.

The sweep report lists 84,651 candidate strings with zero verified new matches.
This generator deliberately copies only its four counters into a portable
header; candidate strings are not imported or queried.

Usage:
  generate_key_sweep_summary.py [report.txt] [header.h]
"""

import os
import re
import sys

FIELDS = ("candidates", "collected", "previously_known", "new_matches")
TOOL = "tools/generate_key_sweep_summary.py"


def parse(path):
    values = {}
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            for name, number in re.findall(r"(\w+)=(\d+)", line):
                if name in FIELDS:
                    values[name] = int(number)
    missing = [name for name in FIELDS if name not in values]
    if missing:
        raise RuntimeError("missing key sweep counters: " + ", ".join(missing))
    return tuple(values[name] for name in FIELDS)


def write_header(path, values):
    lines = [
        "#pragma once",
        "",
        "#include \"mmu/core/Types.h\"",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/key_names_discovered.txt." % TOOL,
        "// Counters only: the 84,651 unverified candidate strings are not",
        "// imported into any verified key-name table.",
        "inline constexpr u32 kKeySweepCandidateCount = %du;" % values[0],
        "inline constexpr u32 kKeySweepCollectedCount = %du;" % values[1],
        "inline constexpr u32 kKeySweepPreviouslyKnownCount = %du;" % values[2],
        "inline constexpr u32 kKeySweepNewMatchCount = %du;" % values[3],
        "",
        "} // namespace mmu",
        "",
    ]
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "docs", "key_names_discovered.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "KeySweepSummary.h")
    write_header(header, parse(report))
    print("key sweep candidates=%d new_matches=%d" %
          (parse(report)[0], parse(report)[3]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
