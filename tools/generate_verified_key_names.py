#!/usr/bin/env python3
"""Derive a C++ lookup table from the verified key-name report.

docs/key_names.txt is generated by tools/crack_hash.py from exact non-reflected
CRC-32 matches against MMU.exe's 0x43c010 dictionary. This tool only copies
those already-verified `hash name` rows into a portable header; it does not
touch the unverified candidate reports key_names_discovered.txt or
key_names_mitm.txt, and it assigns no gameplay meaning to a name.

Usage:
  generate_verified_key_names.py [report.txt] [header.h]
"""

import os
import re
import sys

ROW_RE = re.compile(r"^(0x[0-9a-fA-F]{8}) ([^\s].*)$")
TOOL = "tools/generate_verified_key_names.py"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path):
    rows = []
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = ROW_RE.match(line.rstrip("\r\n"))
            if match:
                rows.append((int(match.group(1), 16), match.group(2)))
    return rows


def write_header(path, rows):
    lines = [
        "#pragma once",
        "",
        '#include "mmu/core/Types.h"',
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/key_names.txt." % TOOL,
        "// Only exact hash matches from tools/crack_hash.py are present;",
        "// unverified candidate lists are not imported. No semantics assigned.",
        "struct VerifiedKeyName {",
        "    u32 hash;",
        "    std::string_view name;",
        "};",
        "",
        "inline constexpr VerifiedKeyName kVerifiedKeyNames[] = {",
    ]
    for key, name in rows:
        lines.append("    {0x%08xu, %s}," % (key, cpp_string(name)))
    lines.extend([
        "};",
        "",
        "inline constexpr std::size_t kVerifiedKeyNameCount =",
        "    sizeof(kVerifiedKeyNames) / sizeof(kVerifiedKeyNames[0]);",
        "",
        "inline std::string_view verifiedKeyName(u32 hash) {",
        "    for (const VerifiedKeyName& row : kVerifiedKeyNames)",
        "        if (row.hash == hash) return row.name;",
        "    return {};",
        "}",
        "",
        "inline bool hasVerifiedKeyName(u32 hash) {",
        "    return !verifiedKeyName(hash).empty();",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "docs", "key_names.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "VerifiedKeyNames.h")
    rows = parse(report)
    write_header(header, rows)
    print("verified key names=%d" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
