#!/usr/bin/env python3
"""Recover the CONTINUE action's stage dispatcher from MMU.exe.

FUN_0050e610 stores the saved stage id in the flow manager at +0x3c and then
builds one of 39 level objects. Ghidra names those constructors and writes the
exact `Level...::vftable` assignment, so the stage id -> level class map is
binary evidence rather than a label guess.

Outputs:
  docs/continue_stages.txt
  core/include/mmu/core/ContinueStageTable.h
"""

import os
import re
import sys

from analyze_rtti import PE


DISPATCHER = "0x50e610"
CASE_RE = re.compile(r"^\s*case\s+(\d+|0x[0-9a-fA-F]+):")
CALL_RE = re.compile(r"\b(FUN_[0-9a-fA-F]+)\(\);")
VFTABLE_RE = re.compile(r"\*param_1\s*=\s*([A-Za-z_][A-Za-z0-9_]*)::vftable")


def decoder_path(root, va):
    return os.path.join(root, "docs", "decompiled", "0x%06x.c" % va)


def collect_stages(pe, root):
    dispatcher = decoder_path(root, int(DISPATCHER, 16))
    if not os.path.isfile(dispatcher):
        raise RuntimeError("missing decompilation: " + dispatcher)

    rows = []
    current = None
    for line in open(dispatcher, encoding="utf-8", errors="replace"):
        match = CASE_RE.match(line)
        if match:
            current = int(match.group(1), 0)
            continue
        match = CALL_RE.search(line)
        if match is None or current is None:
            continue
        va = int(match.group(1)[4:], 16)
        if not pe.in_text(va):
            raise RuntimeError("stage constructor 0x%x is outside .text" % va)
        path = decoder_path(root, va)
        if not os.path.isfile(path):
            raise RuntimeError("missing stage constructor: " + path)
        class_name = None
        for ctor_line in open(path, encoding="utf-8", errors="replace"):
            vft = VFTABLE_RE.search(ctor_line)
            if vft:
                class_name = vft.group(1)
                break
        if class_name is None:
            raise RuntimeError("no vftable assignment in 0x%x" % va)
        rows.append({
            "stageId": current,
            "constructor": va,
            "className": class_name,
        })

    seen = set()
    for row in rows:
        if row["stageId"] in seen:
            raise RuntimeError("duplicate stage id %d" % row["stageId"])
        seen.add(row["stageId"])
    rows.sort(key=lambda row: row["stageId"])
    return rows


def write_report(rows, path):
    present = {row["stageId"] for row in rows}
    missing = [i for i in range(1, max(present) + 1) if i not in present]
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by tools/analyze_continue_stages.py\n")
        out.write("Source: switch(param_2) in docs/decompiled/0x50e610.c and the\n")
        out.write("Level...::vftable assignment in each decompiled constructor.\n")
        out.write("stages=%d missing=%s\n\n" % (
            len(rows), ",".join(str(i) for i in missing) or "-"))
        for row in rows:
            out.write("stage=%2d 0x%02x constructor=0x%06x class=%s\n" % (
                row["stageId"], row["stageId"], row["constructor"],
                row["className"]))


def write_header(rows, path):
    with open(path, "w", encoding="utf-8") as out:
        out.write("#pragma once\n\n")
        out.write("#include \"mmu/core/Types.h\"\n\n")
        out.write("#include <cstddef>\n")
        out.write("#include <string_view>\n\n")
        out.write("namespace mmu {\n\n")
        out.write("// Generated by tools/analyze_continue_stages.py.\n")
        out.write("// The saved stage id is manager field +0x3c; action 0x0a passes it to\n")
        out.write("// FUN_0050e610, which constructs the level class listed here.\n")
        out.write("struct RecoveredContinueStage {\n")
        out.write("    u32 stageId;\n")
        out.write("    u32 constructorVa;\n")
        out.write("    std::string_view className;\n")
        out.write("};\n\n")
        out.write("inline constexpr RecoveredContinueStage kRecoveredContinueStages[] = {\n")
        for row in rows:
            out.write("    {%du, 0x%06xu, \"%s\"},\n" % (
                row["stageId"], row["constructor"], row["className"]))
        out.write("};\n\n")
        out.write("inline constexpr std::size_t kRecoveredContinueStageCount =\n")
        out.write("    sizeof(kRecoveredContinueStages) / sizeof(kRecoveredContinueStages[0]);\n\n")
        out.write("inline const RecoveredContinueStage* findContinueStage(u32 stageId) {\n")
        out.write("    for (const RecoveredContinueStage& row : kRecoveredContinueStages)\n")
        out.write("        if (row.stageId == stageId) return &row;\n")
        out.write("    return nullptr;\n")
        out.write("}\n\n")
        out.write("} // namespace mmu\n")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "docs", "continue_stages.txt")
    header = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        root, "core", "include", "mmu", "core", "ContinueStageTable.h")
    pe = PE(open(sys.argv[1], "rb").read())
    rows = collect_stages(pe, root)
    write_report(rows, report)
    write_header(rows, header)
    print("stages=%d report=%s header=%s" % (len(rows), report, header))
    return 0


if __name__ == "__main__":
    sys.exit(main())
