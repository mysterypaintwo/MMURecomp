#!/usr/bin/env python3
"""Copy docs/rtti_classes.txt into a portable, read-only string table.

The first line ('type_info') and every following decoded RTTI class name are
copied verbatim in original order. No class is renamed or classified.

Usage:
  generate_rtti_class_names_header.py [report.txt] [header.h]
"""

import os
import sys

TOOL = "tools/generate_rtti_class_names_header.py"


def cpp_string(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "docs", "rtti_classes.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "RttiClassNames.h")
    with open(report, "r", encoding="utf-8") as handle:
        names = [line.rstrip("\r\n") for line in handle if line.strip()]
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/rtti_classes.txt." % TOOL,
        "// Exact decoded type_info/class-name lines are copied verbatim.",
        "inline constexpr std::string_view kRttiClassNames[] = {",
    ]
    for name in names:
        out.append("    %s," % cpp_string(name))
    out.extend([
        "};",
        "",
        "inline constexpr std::size_t kRttiClassNameCount =",
        "    sizeof(kRttiClassNames) / sizeof(kRttiClassNames[0]);",
        "",
        "inline std::size_t rttiClassNameIndex(std::string_view name) {",
        "    for (std::size_t i = 0; i < kRttiClassNameCount; ++i)",
        "        if (kRttiClassNames[i] == name) return i;",
        "    return kRttiClassNameCount;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(header, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print("rtti class names=%d" % len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
