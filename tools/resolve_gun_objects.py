#!/usr/bin/env python3
"""Match each constructor's hashed GameParam keys to its guns.mmu GameObject.

`extract_gun_params.py` reports which hashed keys each class constructor reads.
Many keys are shared by every object, but each class also reads a few rare
keys. The GameObject that owns all of a class's rare keys is its .xgun object.

Usage:
  python3 tools/resolve_gun_objects.py MMU.exe Assets/guns.mmu docs/gun_params.txt \
      core/include/mmu/core/GunParams.h
"""

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from extract_gun_params import load_guns
from google.protobuf import descriptor_pool, message_factory
from extract_protos import PROTO_FILES, recover

# Classes whose owning .xgun object was identified from constructor xrefs rather
# than from sound-path hints. Telly's object 0xaabc064d is the one whose getter
# constants match the recovered 30/60/-53/26 parameters.
OBJECT_OVERRIDES = {
    'Telly': 0xaabc064d,
}

CLASS_NAMES = {}
for line in (pathlib.Path(__file__).resolve().parent.parent / 'docs' / 'vtables.txt') \
        .read_text(encoding='utf8').splitlines():
    m = re.match(r'\.\?AV([^@]+)@@\s+vftable RVA .*\(VA (0x[0-9a-f]+)\)', line)
    if m:
        CLASS_NAMES[int(m.group(2), 16)] = m.group(1)


def cfloat(value):
    text = repr(float(value))
    if '.' not in text and 'e' not in text and 'E' not in text:
        text += '.0'
    return text + 'f'


def main():
    exe, guns_path, report, out = sys.argv[1:5]
    params = load_guns(exe, guns_path)
    objects = {}
    for key, values in params.items():
        for obj_key, value in values:
            objects.setdefault(obj_key, {})[key] = value

    # Sound paths retain the source directory of each .xgun object. That is a
    # far stronger class hint than overlapping shared parameter keys.
    exe_data = pathlib.Path(exe).read_bytes()
    pool = descriptor_pool.DescriptorPool()
    for name in ('sdl', 'animation', 'cutscene', 'gun', 'level', 'savedgame'):
        pool.Add(recover(exe_data, PROTO_FILES[name]))
    cls = message_factory.GetMessageClass(pool.FindMessageTypeByName('mmu.Guns'))
    guns = cls()
    guns.ParseFromString(pathlib.Path(guns_path).read_bytes())
    dirs = {}
    for obj in guns.guns:
        paths = ' '.join(s.path for s in obj.sounds if s.path).lower()
        tokens = set(re.findall(r'[\\/]([^\\/]+)[\\/]', paths))
        dirs[obj.key] = tokens

    # Build class -> set of key hashes referenced from its constructor.
    classes = {}
    current = None
    for line in pathlib.Path(report).read_text(encoding='utf8').splitlines():
        m = re.match(r'vftable (0x[0-9a-f]+)', line)
        if m:
            current = int(m.group(1), 16)
            classes.setdefault(current, set())
        elif current and (m := re.search(r'key=(0x[0-9a-f]{8})', line)):
            classes[current].add(int(m.group(1), 16))

    resolved = {}
    for vft, keys in sorted(classes.items()):
        name = CLASS_NAMES.get(vft, f'vftable_0x{vft:x}')
        needle = name.lower().replace('boss', 'boss')
        by_dir = [obj_key for obj_key, tokens in dirs.items() if needle in tokens]
        if by_dir:
            # Prefer the directory match with the most constructor keys.
            best_key = max(by_dir, key=lambda k: len(keys & objects[k].keys()))
            best_params = objects[best_key]
        else:
            scored = []
            for obj_key, obj_params in objects.items():
                missing = keys - obj_params.keys()
                weight = sum(1.0 / max(1, len(params[k])) for k in missing)
                scored.append((weight, len(missing), obj_key, obj_params))
            scored.sort()
            best_weight, best_missing, best_key, best_params = scored[0]
            if not keys or best_missing > 6:
                continue
        if name in OBJECT_OVERRIDES and OBJECT_OVERRIDES[name] in objects:
            best_key = OBJECT_OVERRIDES[name]
            best_params = objects[best_key]
        resolved[name] = (best_key, best_params, keys)

    lines = [
        '// Generated by tools/resolve_gun_objects.py -- do not edit by hand.',
        '// Hashed GameParam keys are read directly from MMU.exe; values come from',
        '// the decoded guns.mmu. The owning object is inferred by key overlap.',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace mmu {',
        '',
        'struct GunParamEntry {',
        '    std::uint32_t key;',
        '    float value;',
        '};',
        '',
        'struct GunObject {',
        '    std::uint32_t key;',
        '    const GunParamEntry* params;',
        '    std::uint32_t paramCount;',
        '};',
        '',
        '// GameParam key names resolved by tools/crack_hash.py. All eight use the',
        '// non-reflected CRC-32 at MMU.exe 0x43c010.',
        'constexpr std::uint32_t kMoveSpeedKey = 0x57469074u;       // "MoveSpeed"',
        'constexpr std::uint32_t kMoveDistanceKey = 0xda1f1441u;    // "MoveDistance"',
        'constexpr std::uint32_t kHitPointsKey = 0xa21be30bu;       // "HitPoints"',
        'constexpr std::uint32_t kTargetHotSpotYKey = 0x42714480u;  // "TargetHotSpotY"',
        'constexpr std::uint32_t kTargetHotSpotXKey = 0x42714481u;  // "TargetHotSpotX"',
        'constexpr std::uint32_t kShootDelayKey = 0xe1e66eb0u;      // "ShootDelay"',
        'constexpr std::uint32_t kJumpHeightKey = 0xfb2481abu;      // "JumpHeight"',
        'constexpr std::uint32_t kExplosionDelayKey = 0xc3ae9999u;  // "ExplosionDelay"',
        'constexpr std::uint32_t kIdleDelayKey = 0xb98e43bdu;       // "IdleDelay"',
        '',
        '// Legacy aliases retained for older reconstruction notes.',
        'constexpr std::uint32_t kSpeedKey = kMoveSpeedKey;',
        'constexpr std::uint32_t kRadiusKey = kMoveDistanceKey;',
        'constexpr std::uint32_t kSpriteKey = kHitPointsKey;',
        'constexpr std::uint32_t kContactLeftKey = kTargetHotSpotYKey;',
        'constexpr std::uint32_t kContactRightKey = kTargetHotSpotXKey;',
        'constexpr std::uint32_t kFireRateKey = kShootDelayKey;',
        'constexpr std::uint32_t kProjectileSpeedKey = kJumpHeightKey;',
        '',
        'inline float gunParam(const GunObject& object, std::uint32_t key, float fallback) {',
        '    for (std::uint32_t i = 0; i < object.paramCount; ++i)',
        '        if (object.params[i].key == key) return object.params[i].value;',
        '    return fallback;',
        '}',
        '',
    ]
    for name, (obj_key, obj_params, keys) in sorted(resolved.items()):
        if name not in ('Telly', 'EZBlock', 'MineE', 'SawPole', 'SuperCannon',
                        'Boss', 'MidBoss', 'WilyBoss', 'WilyMachine', 'WilyCapsule'):
            continue
        safe = re.sub(r'[^A-Za-z0-9_]', '_', name)
        lines.append(f'static const GunParamEntry k{safe}Params[] = {{')
        for k, v in sorted(obj_params.items()):
            lines.append(f'    {{0x{k:08x}u, {cfloat(v)}}},')
        lines.append('};')
        lines.append(f'static const GunObject k{safe} = {{0x{obj_key:08x}u, '
                     f'k{safe}Params, {len(obj_params)}}};')
        lines.append('')
    lines += ['} // namespace mmu', '']
    pathlib.Path(out).write_text('\n'.join(lines))

    print(f'resolved {len(resolved)} classes')
    for name in ('Telly', 'EZBlock', 'MineE', 'SawPole', 'SuperCannon',
                 'Boss', 'MidBoss', 'WilyBoss', 'WilyMachine', 'WilyCapsule'):
        if name in resolved:
            obj, _, keys = resolved[name]
            print(f'  {name:14s} obj=0x{obj:08x} keys={len(keys)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
