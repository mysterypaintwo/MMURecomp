#!/usr/bin/env python3
"""Recover level/scene names and RTTI class names from MMU.exe.

The shipped .mmu databases store only numeric keys, but the executable still
contains the 791 editor-side ``\\Levels\\<Name>.xscn`` resource paths in the
same order as the scenes in levels.mmu.  This script writes:

  tools/scene_names.inc    C++ string table included by bake_assets.cpp
  docs/rtti_classes.txt    recovered non-protobuf RTTI class names

Usage: python3 tools/extract_metadata.py /path/to/MMU.exe
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def cpp_string(text):
    out = '"'
    for ch in text:
        if ch == '\\':
            out += '\\\\'
        elif ch == '"':
            out += '\\"'
        elif 32 <= ord(ch) < 127:
            out += ch
        else:
            out += '\\x%02x' % ord(ch)
    return out + '"'


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    exe = pathlib.Path(sys.argv[1]).read_bytes()

    strings = [m.group() for m in re.finditer(rb'[\x20-\x7e]{6,}\x00', exe)]
    scenes = [s[:-1].decode('latin1') for s in strings
              if s.lower().endswith(b'.xscn\x00')]
    if len(scenes) != 791:
        print(f'warning: expected 791 .xscn paths, found {len(scenes)}')

    inc = ROOT / 'tools' / 'scene_names.inc'
    with inc.open('w') as f:
        f.write('// Generated by tools/extract_metadata.py from MMU.exe. Do not edit.\n')
        f.write('// Editor-side scene resource paths, in levels.mmu scene order.\n')
        f.write(f'inline const char* const kSceneNames[] = {{\n')
        for name in scenes:
            f.write('    ' + cpp_string(name) + ',\n')
        f.write('};\n')
    print(f'wrote {inc}: {len(scenes)} scene names')

    rtti = []
    for m in re.finditer(rb'\.\?AV([A-Za-z_?$][A-Za-z0-9_?$@]*?)@@', exe):
        name = m.group(1).decode('latin1')
        if name.startswith('google') or 'protobuf' in name or '::' in name:
            continue
        if name not in rtti:
            rtti.append(name)
    docs = ROOT / 'docs'
    docs.mkdir(exist_ok=True)
    out = docs / 'rtti_classes.txt'
    out.write_text('\n'.join(rtti) + '\n')
    print(f'wrote {out}: {len(rtti)} class names')
    return 0


if __name__ == '__main__':
    sys.exit(main())
