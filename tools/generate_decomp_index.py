#!/usr/bin/env python3
"""Generate a portable index for filesystem-only decompilation evidence.

The decompiled C files and xref reports are offline artifacts. This tool copies
only their raw identifiers into a header so the SDL2 harness can query them on
Switch without reading docs/ at runtime. No function is named or classified
beyond the exact VA/class strings present in the generated files.

Usage:
  generate_decomp_index.py [root] [header.h]
"""

import os
import re
import sys

FILE_RE = re.compile(r"^(?:0x)?([0-9a-fA-F]{6,8})\.c$")
INDEX_RE = re.compile(r"^(\S+) (0x[0-9a-f]+) refs=(\d+)$")
REF_RE = re.compile(r"^\s+\S+ @ (0x[0-9a-f]+)$")
VA_RE = re.compile(r"^0x[0-9a-fA-F]+$")
XREF_RE = re.compile(r"^(\S+) (0x[0-9a-fA-F]+)$")
TOOL = "tools/generate_decomp_index.py"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_lines(path):
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        return handle.read().splitlines()


def collect(root):
    decompiled = []
    decompiled_dir = os.path.join(root, "docs", "decompiled")
    for name in os.listdir(decompiled_dir):
        match = FILE_RE.match(name)
        if match:
            decompiled.append(int(match.group(1), 16))
    decompiled = sorted(set(decompiled))

    xref_rows = []
    xref_path = os.path.join(root, "docs", "decompiled_xref", "index.txt")
    current = None
    for line in read_lines(xref_path):
        match = INDEX_RE.match(line)
        if match:
            current = {
                "class": match.group(1),
                "stringVa": int(match.group(2), 16),
                "refs": int(match.group(3)),
                "refVas": [],
            }
            xref_rows.append(current)
            continue
        match = REF_RE.match(line)
        if match and current is not None:
            current["refVas"].append(int(match.group(1), 16))

    string_xrefs = {}
    xref_report = os.path.join(root, "tools", "string_xrefs.txt")
    for line in read_lines(xref_report):
        match = XREF_RE.match(line.strip())
        if match:
            string_xrefs[match.group(1)] = int(match.group(2), 16)
    for row in xref_rows:
        if row["class"] in string_xrefs:
            row["stringVaFromReport"] = string_xrefs[row["class"]]

    target_lists = []
    for name, path in (
        ("targets", "decompile_targets.txt"),
        ("flow", "decompile_flow_targets.txt"),
        ("dispatcher", "decompile_dispatcher_targets.txt"),
    ):
        values = []
        for line in read_lines(os.path.join(root, "tools", path)):
            text = line.strip()
            if VA_RE.match(text):
                values.append(int(text, 16))
        target_lists.append((name, values))
    unique_targets = sorted({va for _, values in target_lists for va in values})
    return decompiled, xref_rows, target_lists, unique_targets


def emit_u32_array(lines, name, values, per_line=8):
    lines.append("inline constexpr u32 %s[] = {" % name)
    for i in range(0, len(values), per_line):
        lines.append("    " + " ".join("0x%06xu," % va for va in values[i:i + per_line]))
    lines.extend([
        "};",
        "inline constexpr std::size_t %sCount =" % name,
        "    sizeof(%s) / sizeof(%s[0]);" % (name, name),
        "",
    ])


def write_header(path, decompiled, xref_rows, target_lists, unique_targets):
    lines = [
        "#pragma once",
        "",
        '#include "mmu/core/Types.h"',
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from offline decompilation reports." % TOOL,
        "// VAs, class names and counts are copied verbatim; no function is",
        "// renamed or classified. This avoids reading docs/ at runtime.",
        "struct DecompStringXref {",
        "    std::string_view className;",
        "    u32 stringVa;",
        "    u8 refCount;",
        "    u32 refVas[4];",
        "};",
        "",
    ]
    emit_u32_array(lines, "kDecompiledFunctionVas", decompiled)
    lines.append("inline constexpr DecompStringXref kDecompStringXrefs[] = {")
    for row in xref_rows:
        ref_vas = list(row["refVas"]) + [0] * (4 - len(row["refVas"]))
        lines.append(
            "    {%s, 0x%06xu, %du, {0x%06xu, 0x%06xu, 0x%06xu, 0x%06xu}}," %
            (cpp_string(row["class"]), row["stringVa"], row["refs"],
             ref_vas[0], ref_vas[1], ref_vas[2], ref_vas[3]))
    lines.extend([
        "};",
        "inline constexpr std::size_t kDecompStringXrefCount =",
        "    sizeof(kDecompStringXrefs) / sizeof(kDecompStringXrefs[0]);",
        "",
    ])
    for name, values in target_lists:
        emit_u32_array(lines, "kDecomp%sTargetVas" % name.capitalize(), values)
    emit_u32_array(lines, "kDecompUniqueTargetVas", unique_targets)
    lines.extend([
        "inline bool hasDecompiledFunction(u32 va) {",
        "    for (u32 row : kDecompiledFunctionVas)",
        "        if (row == va) return true;",
        "    return false;",
        "}",
        "",
        "inline const DecompStringXref* decompStringXref(std::string_view className) {",
        "    for (const DecompStringXref& row : kDecompStringXrefs)",
        "        if (row.className == className) return &row;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "DecompIndex.h")
    decompiled, xrefs, targets, unique = collect(root)
    write_header(header, decompiled, xrefs, targets, unique)
    print("decompiled=%d xrefs=%d targets=%d unique_targets=%d" %
          (len(decompiled), len(xrefs),
           sum(len(values) for _, values in targets), len(unique)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
