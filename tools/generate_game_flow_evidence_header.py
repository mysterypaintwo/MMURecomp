#!/usr/bin/env python3
"""Copy docs/game_flow.txt into a portable, read-only string table.

Every line is copied verbatim as a C++ string literal, including blank lines
and the report's own notes. No slot is classified and no transition is inferred.

Usage:
  generate_game_flow_evidence_header.py [report.txt] [header.h]
"""

import os
import sys

TOOL = "tools/generate_game_flow_evidence_header.py"


def cpp_string(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "docs", "game_flow.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "GameFlowEvidenceTable.h")
    with open(report, "r", encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/game_flow.txt." % TOOL,
        "// Exact report lines and order are copied verbatim. Identifiers such as",
        "// 'global_cue_or_state_setter' are raw source text, not gameplay labels.",
        "inline constexpr std::string_view kGameFlowEvidenceLines[] = {",
    ]
    for line in lines:
        out.append("    %s," % cpp_string(line))
    out.extend([
        "};",
        "",
        "inline constexpr std::size_t kGameFlowEvidenceLineCount =",
        "    sizeof(kGameFlowEvidenceLines) / sizeof(kGameFlowEvidenceLines[0]);",
        "",
        "inline std::string_view gameFlowEvidenceLine(std::size_t number) {",
        "    return number >= 1 && number <= kGameFlowEvidenceLineCount",
        "               ? kGameFlowEvidenceLines[number - 1]",
        "               : std::string_view();",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(header, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print("game flow evidence lines=%d" % len(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
