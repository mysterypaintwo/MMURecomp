#!/usr/bin/env python3
"""Derive an unverified candidate table from docs/key_names_mitm.txt.

The MITM tool reports exact CRC-32 matches from a curated vocabulary, but those
strings have not been reviewed as actual GameParam names. This generator keeps
them in a separate header with an explicit `unverified` label. It never writes
to VerifiedKeyNames.h or tools/crack_hash.py's KNOWN_KEY_NAMES.

Usage:
  generate_key_name_candidates.py [report.txt] [header.h]
"""

import os
import re
import sys

ROW_RE = re.compile(r"^(0x[0-9a-fA-F]{8}) ([^\s].*)$")
TOOL = "tools/generate_key_name_candidates.py"


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(path):
    rows = []
    reported = None
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = re.match(r"^new_matches=(\d+)$", line.strip())
            if match:
                reported = int(match.group(1))
            match = ROW_RE.match(line.rstrip("\r\n"))
            if match:
                rows.append((int(match.group(1), 16), match.group(2)))
    if reported is not None and reported != len(rows):
        raise RuntimeError("candidate count mismatch")
    return rows


def write_header(path, rows):
    lines = [
        "#pragma once",
        "",
        '#include "mmu/core/Types.h"',
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace mmu {",
        "",
        "// Generated by %s from docs/key_names_mitm.txt." % TOOL,
        "// These are exact CRC-32 matches from a curated vocabulary, NOT verified",
        "// GameParam names. They are intentionally absent from VerifiedKeyNames.h.",
        "struct UnverifiedKeyNameCandidate {",
        "    u32 hash;",
        "    std::string_view name;",
        "};",
        "",
        "inline constexpr UnverifiedKeyNameCandidate kUnverifiedKeyNameCandidates[] = {",
    ]
    for key, name in rows:
        lines.append("    {0x%08xu, %s}," % (key, cpp_string(name)))
    lines.extend([
        "};",
        "",
        "inline constexpr std::size_t kUnverifiedKeyNameCandidateCount =",
        "    sizeof(kUnverifiedKeyNameCandidates) /",
        "    sizeof(kUnverifiedKeyNameCandidates[0]);",
        "",
        "inline std::string_view unverifiedKeyNameCandidate(u32 hash) {",
        "    for (const UnverifiedKeyNameCandidate& row : kUnverifiedKeyNameCandidates)",
        "        if (row.hash == hash) return row.name;",
        "    return {};",
        "}",
        "",
        "} // namespace mmu",
        "",
    ])
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "docs", "key_names_mitm.txt")
    header = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "core", "include", "mmu", "core", "KeyNameCandidates.h")
    rows = parse(report)
    write_header(header, rows)
    print("unverified key name candidates=%d" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
