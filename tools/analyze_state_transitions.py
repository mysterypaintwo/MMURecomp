#!/usr/bin/env python3
"""Recover observed state/cue transitions from MMU.exe vtable callbacks.

The companion analyze_game_flow.py reports the same evidence in prose. This
tool emits a machine-readable table of (class, vtable slot, callback address,
call address, target name, setter kind) pairs for every setState (0x4405c0) or
global cue setter (0x4026b0) call found in Menu*/Level* virtual functions.

Outputs:
  docs/state_transitions.txt
  core/include/mmu/core/RegisteredStateTransitions.h

The generated C++ table is evidence only. It records what the binary calls;
it does not assert ordering, timing, or screen destinations.
"""

import os
import sys

from capstone import CS_ARCH_X86, CS_MODE_32, Cs
from capstone.x86 import X86_OP_IMM

from analyze_game_flow import GLOBAL_SET, SET_STATE, cstring, short_class, target_of
from analyze_rtti import PE
from analyze_state_names import (cpp_string, name_before, registration_sites,
                                 state_hash)
from disasm import find_vftables

SCAN_LIMIT = 0x700
SET_FLAGS = {"setState": 1, "cue": 2}


def scan_callback(pe, va):
    off = pe.rva_to_off(va - pe.image_base)
    if off is None:
        return []
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    records = []
    last_string = None
    for ins in md.disasm(pe.data[off:off + SCAN_LIMIT], va):
        if ins.mnemonic in ("int3", "ret", "retf"):
            break
        for op in ins.operands:
            if op.type == X86_OP_IMM:
                text = cstring(pe, op.imm & 0xFFFFFFFF)
                if text:
                    last_string = text
        if ins.mnemonic == "call":
            target = target_of(ins)
            if target in (SET_STATE, GLOBAL_SET) and last_string:
                kind = "setState" if target == SET_STATE else "cue"
                records.append((ins.address, kind, last_string))
                last_string = None
    return records


def collect(pe):
    registered = set()
    for site in registration_sites(pe):
        name = name_before(pe, site)
        if name:
            registered.add(name)

    records = []
    for class_name, entries in find_vftables(pe).items():
        simple = short_class(class_name)
        if "@mmu" in simple or not ("Menu" in simple or "Level" in simple):
            continue
        kind = "menu" if "Menu" in simple else "level"
        for vft, funcs in entries:
            for slot, func_va in enumerate(funcs):
                if func_va < pe.image_base:
                    continue
                for call_va, setter, target in scan_callback(pe, func_va):
                    records.append({
                        "class": simple,
                        "kind": kind,
                        "vft": vft,
                        "slot": slot,
                        "func": func_va,
                        "call": call_va,
                        "setter": setter,
                        "target": target,
                        "hash": state_hash(target),
                        "registered": target in registered,
                    })
    records.sort(key=lambda r: (r["kind"], r["class"], r["vft"], r["slot"],
                                r["call"]))
    return records


def write_report(records, path):
    with open(path, "w", encoding="utf-8") as out:
        out.write("Generated by tools/analyze_state_transitions.py\n")
        out.write("Source: setState 0x4405c0 and cue setter 0x4026b0 calls in "
                  "Menu*/Level* vtable callbacks.\n")
        out.write("Evidence only: no ordering, timing, or destination is inferred.\n")
        out.write("records=%d setState=%d cue=%d\n\n" % (
            len(records),
            sum(1 for r in records if r["setter"] == "setState"),
            sum(1 for r in records if r["setter"] == "cue")))
        current = None
        for r in records:
            key = (r["class"], r["vft"])
            if key != current:
                current = key
                out.write("=== %s (%s) vftable 0x%x ===\n" %
                          (r["class"], r["kind"], r["vft"]))
            registered = ("n/a" if r["setter"] == "cue"
                          else "yes" if r["registered"] else "no")
            out.write("  slot %-2d func=0x%06x call=0x%06x %-8s "
                      "hash=0x%08x registered=%-3s %s\n" % (
                          r["slot"], r["func"], r["call"], r["setter"],
                          r["hash"], registered, r["target"]))
        out.write("\n")


def write_header(records, path):
    with open(path, "w", encoding="utf-8") as out:
        out.write("#pragma once\n\n")
        out.write("#include \"mmu/core/Types.h\"\n\n")
        out.write("#include <cstddef>\n")
        out.write("#include <string_view>\n\n")
        out.write("namespace mmu {\n\n")
        out.write("// Generated by tools/analyze_state_transitions.py. Each row is one\n")
        out.write("// observed setter call in a Menu*/Level* vtable callback. Flags: 1 = setState,\n")
        out.write("// 2 = global cue setter. Behaviour and destinations are not inferred.\n")
        out.write("struct RegisteredStateTransition {\n")
        out.write("    u32 targetHash;\n")
        out.write("    u32 callVa;\n")
        out.write("    u32 functionVa;\n")
        out.write("    u16 vtableSlot;\n")
        out.write("    u8 flags;\n")
        out.write("    u8 reserved;\n")
        out.write("    std::string_view className;\n")
        out.write("    std::string_view targetName;\n")
        out.write("};\n\n")
        out.write("inline constexpr RegisteredStateTransition kRegisteredStateTransitions[] = {\n")
        for r in records:
            out.write("    {0x%08xu, 0x%06xu, 0x%06xu, %du, %du, 0u, \"%s\", \"%s\"},\n" % (
                r["hash"], r["call"], r["func"], r["slot"],
                SET_FLAGS[r["setter"]], cpp_string(r["class"]),
                cpp_string(r["target"])))
        out.write("};\n\n")
        out.write("inline constexpr std::size_t kRegisteredStateTransitionCount =\n")
        out.write("    sizeof(kRegisteredStateTransitions) / sizeof(kRegisteredStateTransitions[0]);\n\n")
        out.write("inline bool hasRegisteredTransitionTo(std::string_view name) {\n")
        out.write("    for (const RegisteredStateTransition& row : kRegisteredStateTransitions)\n")
        out.write("        if (row.targetName == name) return true;\n")
        out.write("    return false;\n")
        out.write("}\n\n")
        out.write("} // namespace mmu\n")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    report = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "docs", "state_transitions.txt")
    header = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        root, "core", "include", "mmu", "core", "RegisteredStateTransitions.h")

    pe = PE(open(sys.argv[1], "rb").read())
    records = collect(pe)
    write_report(records, report)
    write_header(records, header)
    print("records=%d setState=%d cue=%d report=%s header=%s" % (
        len(records),
        sum(1 for r in records if r["setter"] == "setState"),
        sum(1 for r in records if r["setter"] == "cue"), report, header))
    return 0


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    raise SystemExit(main())
